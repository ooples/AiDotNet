"""Original AudioCraft subsampled sampler, with every draw and intermediate retained."""
import argparse
import base64
import importlib.util
import json
from pathlib import Path
import subprocess
import struct
from types import SimpleNamespace
from unittest.mock import patch
import torch

parser = argparse.ArgumentParser()
parser.add_argument('--source', type=Path, required=True)
args = parser.parse_args()
source = args.source / 'audiocraft/modules/diffusion_schedule.py'
spec = importlib.util.spec_from_file_location('original_diffusion_schedule', source)
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
torch.set_num_threads(1)
torch.manual_seed(229467)
cases = []
for custom, scale, clip in [(False, 1., 5.), (True, .7, .4)]:
    schedule = module.NoiseSchedule(beta_t0=1e-5, beta_t1=.029, beta_exp=7.5,
        num_steps=1000, device='cpu', noise_scale=scale, clip=clip)
    # Original sampler always constructs its schedule in float32, even for a float64 model.
    initial = torch.randn(2, 1, 19, dtype=torch.float64) * 2
    condition = torch.randn(2, 1, 19, dtype=torch.float64)
    draws = []
    visited = []
    class ExplicitEstimate(torch.nn.Module):
        def forward(self, current, step, condition):
            visited.append(step)
            return SimpleNamespace(sample=current * .17 + condition * .23 + step * .0001)
    original_randn = torch.randn_like
    def draw(value):
        result = original_randn(value)
        draws.append(result.flatten().tolist())
        return result
    steps = [999, 650, 123, 0] if custom else None
    with patch('torch.randn_like', side_effect=draw):
        trajectory = schedule.generate_subsampled(ExplicitEstimate(), initial, steps, condition, return_list=True)
    original_visited = list(visited)
    schedule.betas = schedule.betas.double()
    replay = iter(draws)
    with patch('torch.randn_like', side_effect=lambda x: torch.tensor(next(replay), dtype=x.dtype).reshape_as(x)):
        matched = schedule.generate_subsampled(ExplicitEstimate(), initial, steps, condition, return_list=True)
    cases.append(dict(custom=custom, steps=steps, scale=scale, clip=clip,
        betas=schedule.betas.tolist(), initial=initial.flatten().tolist(), condition=condition.flatten().tolist(),
        draws=draws, visited=original_visited, trajectory=[x.flatten().tolist() for x in trajectory],
        matched_float64_trajectory=[x.flatten().tolist() for x in matched]))
destination = Path(__file__).resolve().parents[2] / 'tests/AiDotNet.Tests/TextToSpeech/ReferenceData/metavoice_multiband_schedule.json'
destination.write_text(json.dumps(dict(source='https://github.com/facebookresearch/audiocraft',
    revision=subprocess.check_output(['git', '-C', str(args.source), 'rev-parse', 'HEAD'], text=True).strip(),
    unchanged_author_sampler=True, explicit_analytic_estimator=True, cases=cases)) + '\n', encoding='utf-8')
print(json.dumps(dict(cases=len(cases), visited=[x['visited'] for x in cases], draws=[len(x['draws']) for x in cases])))

# The released preset has one fixed float32 power schedule across all four bands.
# Preserve the author's exact coefficients as hyperparameters, not fitted weights.
encoded = base64.b64encode(struct.pack('<1000f', *cases[0]['betas'])).decode()
chunks = [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
generated = '// Generated by tools/reference-data/metavoice_multiband_schedule.py from AudioCraft 1.2.0.\n'
generated += 'namespace AiDotNet.TextToSpeech.VoiceCloning;\n\ninternal static class MetaVoiceDiffusionBetas\n{\n'
generated += '    // beta_t0=1e-5, beta_t1=.029, beta_exp=7.5, num_steps=1000; original float32 construction.\n'
generated += '    private const string Encoded =\n' + '\n'.join('        "' + part + '"' + (';' if i == len(chunks) - 1 else ' +') for i, part in enumerate(chunks)) + '\n'
generated += '''    internal static double[] CreateReleaseSchedule()
    {
        var bytes = Convert.FromBase64String(Encoded);
        var values = new double[1000];
        for (int i = 0; i < values.Length; i++)
        {
            var scalar = new byte[4]; Array.Copy(bytes, 4 * i, scalar, 0, 4);
            if (!BitConverter.IsLittleEndian) Array.Reverse(scalar);
            values[i] = BitConverter.ToSingle(scalar, 0);
        }
        return values;
    }
}
'''
Path(__file__).resolve().parents[2].joinpath('src/TextToSpeech/VoiceCloning/MetaVoiceDiffusionBetas.cs').write_text(generated, encoding='utf-8')
