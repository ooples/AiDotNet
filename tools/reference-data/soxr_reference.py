"""librosa 0.10.2's default resampler (res_type 'soxr_hq': python-soxr 1.1.0's resample at quality HQ, then fix_length to
ceil(n * target / orig)) through libsoxr itself, the copy python-soxr 1.1.0 vendors.

HQ asks for 20 bits, and libsoxr computes a quality of 20 bits or fewer in single precision (its cr32 engine, with SIMD
where the CPU has it); the reference builds the vendored libsoxr with its double-precision engine only (cr64, Ooura's FFT,
no SIMD) and passes SOXR_DOUBLE_PRECISION, the library's own switch to compute any quality in double precision (a
precision patch: the same filters, stages and arithmetic in float64). It drives libsoxr through ctypes exactly as
python-soxr's csoxr_split_ch does (soxr_process in blocks of max(1000, 48000 * in / out) input samples into a buffer of
n * out / in + 1, then a flush) and checks that python-soxr's own float32 output agrees to single precision.

Records in tests/AiDotNet.Tests/Audio/ReferenceData/soxr_reference.json, for rate pairs that take each of libsoxr's stage
kinds (half-band decimation, DFT stages with power-of-two and other factors, frequency-domain decimation, the poly-phase
stage), float32 noise from a 64-bit LCG (regenerated by the test from its seed, length and scale) and librosa.resample's
output.
Default: verify; --write: regenerate. Runs in the megatts-ref-soxr Docker image (megatts-ref plus the libsoxr build):
  docker run --rm -v <repo>:/work -w /work megatts-ref-soxr python tools/reference-data/soxr_reference.py --write
"""
import argparse
import ctypes
import ctypes.util
import os
import sys
import types

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
try:
    import torch  # noqa: F401  (_fixture records its version)
except ImportError:
    sys.modules["torch"] = types.SimpleNamespace(__version__="not installed")
import _fixture  # noqa: E402

FIXTURE = "tests/AiDotNet.Tests/Audio/ReferenceData/soxr_reference.json"
PAIRS = [(24000, 16000), (44100, 24000), (48000, 24000), (16000, 24000), (22050, 24000), (32000, 24000), (8000, 24000),
         (96000, 24000), (11025, 24000), (192000, 16000), (24000, 48000), (44100, 16000),
         # Irrational to libsoxr (no denominator up to 2048): the interpolated poly-phase stages.
         (44100, 23999), (8001, 24000), (24000, 16001), (48000, 7919)]
SOXR_HQ, SOXR_DOUBLE_PRECISION, SOXR_FLOAT64_S = 4, 16, 5


class QualitySpec(ctypes.Structure):
    _fields_ = [("precision", ctypes.c_double), ("phase_response", ctypes.c_double), ("passband_end", ctypes.c_double),
                ("stopband_begin", ctypes.c_double), ("e", ctypes.c_void_p), ("flags", ctypes.c_ulong)]


class IoSpec(ctypes.Structure):
    _fields_ = [("itype", ctypes.c_int), ("otype", ctypes.c_int), ("scale", ctypes.c_double), ("e", ctypes.c_void_p),
                ("flags", ctypes.c_ulong)]


def load():
    lib = ctypes.CDLL(ctypes.util.find_library("soxr") or "libsoxr.so")
    lib.soxr_quality_spec.restype = QualitySpec
    lib.soxr_quality_spec.argtypes = [ctypes.c_ulong, ctypes.c_ulong]
    lib.soxr_io_spec.restype = IoSpec
    lib.soxr_io_spec.argtypes = [ctypes.c_int, ctypes.c_int]
    lib.soxr_create.restype = ctypes.c_void_p
    lib.soxr_create.argtypes = [ctypes.c_double, ctypes.c_double, ctypes.c_uint, ctypes.POINTER(ctypes.c_char_p),
                                ctypes.POINTER(IoSpec), ctypes.POINTER(QualitySpec), ctypes.c_void_p]
    lib.soxr_process.restype = ctypes.c_char_p
    lib.soxr_process.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_size_t, ctypes.c_void_p, ctypes.c_void_p,
                                 ctypes.c_size_t, ctypes.POINTER(ctypes.c_size_t)]
    lib.soxr_engine.restype = ctypes.c_char_p
    lib.soxr_engine.argtypes = [ctypes.c_void_p]
    lib.soxr_delete.argtypes = [ctypes.c_void_p]
    return lib


def soxr_split_ch(lib, x, in_rate, out_rate):
    """csoxr_split_ch for one channel of float64."""
    ilen = len(x)
    olen = int(ilen * out_rate / in_rate + 1)
    io = lib.soxr_io_spec(SOXR_FLOAT64_S, SOXR_FLOAT64_S)
    q = lib.soxr_quality_spec(SOXR_HQ, SOXR_DOUBLE_PRECISION)
    err = ctypes.c_char_p()
    s = lib.soxr_create(in_rate, out_rate, 1, ctypes.byref(err), ctypes.byref(io), ctypes.byref(q), None)
    assert not err.value, err.value
    assert lib.soxr_engine(s) == b"cr64", lib.soxr_engine(s)
    div_len = int(max(1000.0, 48000 * in_rate / out_rate))
    x = np.ascontiguousarray(x, dtype=np.float64)
    y = np.zeros(olen, dtype=np.float64)
    out_pos = 0
    odone = ctypes.c_size_t()
    for idx in range(0, ilen, div_len):
        ip = (ctypes.c_void_p * 1)(x.ctypes.data + 8 * idx)
        op = (ctypes.c_void_p * 1)(y.ctypes.data + 8 * out_pos)
        e = lib.soxr_process(s, ip, min(div_len, ilen - idx), None, op, olen - out_pos, ctypes.byref(odone))
        assert not e, e
        out_pos += odone.value
    op = (ctypes.c_void_p * 1)(y.ctypes.data + 8 * out_pos)
    e = lib.soxr_process(s, None, 0, None, op, olen - out_pos, ctypes.byref(odone))
    assert not e, e
    out_pos += odone.value
    lib.soxr_delete(s)
    return y[:out_pos]


def librosa_resample(lib, y, orig_sr, target_sr):
    """librosa.resample(y, orig_sr=..., target_sr=..., res_type='soxr_hq') with the resampler above."""
    import librosa.util
    if orig_sr == target_sr:
        return y
    n_samples = int(np.ceil(y.shape[-1] * (float(target_sr) / orig_sr)))
    return librosa.util.fix_length(soxr_split_ch(lib, y, orig_sr, target_sr), size=n_samples, axis=-1)


def lcg_noise(count, seed, scale):
    """Uniform noise from a 64-bit LCG (Knuth's MMIX constants): the top 24 bits of each state, centred and scaled, to
    float32. Integer and exact arithmetic, so the test regenerates the same samples."""
    state, out = seed, np.empty(count)
    for i in range(count):
        state = (state * 6364136223846793005 + 1442695040888963407) % (1 << 64)
        out[i] = ((state >> 40) / 16777216.0 - 0.5) * scale
    return out.astype(np.float32).astype(np.float64)


def signals(orig, target, k):
    sigs = {"noise": lcg_noise(int(orig * 0.12), 2 * k + 1, 0.4), "short": lcg_noise(37, 2 * k + 2, 0.6)}
    if (orig, target) == (24000, 16000):
        # Longer than python-soxr's block of 48000 * in / out samples, so the stream crosses a block boundary.
        sigs["long"] = lcg_noise(80000, 999, 0.2)
    return sigs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    import librosa
    import soxr
    assert soxr.__version__ == "1.1.0" and librosa.__version__ == "0.10.2.post1", (soxr.__version__, librosa.__version__)
    lib = load()
    stored = None if args.write else _fixture.load(FIXTURE)
    cases = []
    worst = 0.0
    for k, (orig, target) in enumerate(PAIRS):
        for name, x in signals(orig, target, k).items():
            y = librosa_resample(lib, x, orig, target)
            release = librosa.resample(x.astype(np.float32), orig_sr=orig, target_sr=target)
            assert release.shape == y.shape, (release.shape, y.shape)
            worst = max(worst, float(np.max(np.abs(release - y))))
            cases.append({"orig": orig, "target": target, "signal": name, "seed": 999 if name == "long" else 2 * k + (1 if name == "noise" else 2),
                          "length": len(x), "scale": {"noise": 0.4, "short": 0.6, "long": 0.2}[name], "output": y.tolist()})
    assert worst < 1e-4, worst
    data = {"cases": cases, "float32_release_max_difference": worst}
    if args.write:
        _fixture.save(FIXTURE, data, __file__)
        print("wrote", FIXTURE, len(cases), "cases; python-soxr float32 within", worst)
        return
    check = _fixture.Comparison("libsoxr HQ (double precision)")
    for a, b in zip(stored["cases"], cases):
        check.floats(f"{a['orig']}->{a['target']} {a['signal']}", a["output"], b["output"], 1e-12, float)
    check.report(exact=False)


if __name__ == "__main__":
    main()
