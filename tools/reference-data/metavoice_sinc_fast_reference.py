"""Reproduce the EFFECTIVE DeepFilterNet sinc_fast filter with pinned Torchaudio 2.1.0.

The legacy alias is not reassigned after its warning, so the unchanged author
kernel takes its Kaiser branch. Both precision tables are fixed DSP coefficients,
not neural weights. The beta tensor retains Torch's original default float32.
"""
import argparse
import ast
import hashlib
import json
import math
from pathlib import Path
import typing
import warnings
import torch

parser = argparse.ArgumentParser()
parser.add_argument('--torchaudio-source', type=Path, required=True)
parser.add_argument('--deepfilter-source', type=Path, required=True)
args = parser.parse_args()
torch.set_num_threads(1)
torch.set_default_dtype(torch.float32)
scope = dict(torch=torch, math=math, warnings=warnings, Optional=typing.Optional,
             Tensor=torch.Tensor, _CPU=torch.device('cpu'))
names = {'_get_sinc_resample_kernel', '_apply_sinc_resample_kernel', 'resample'}
tree = ast.parse(args.torchaudio_source.read_text(encoding='utf-8'))
nodes = [x for x in tree.body if isinstance(x, ast.FunctionDef) and x.name in names]
assert len(nodes) == 3
exec(compile(ast.Module(body=nodes, type_ignores=[]), str(args.torchaudio_source), 'exec'), scope)
df_scope = dict(Dict=typing.Dict, Any=typing.Any)
df_path = args.deepfilter_source / 'DeepFilterNet/df/io.py'
node = next(x for x in ast.parse(df_path.read_text(encoding='utf-8')).body
            if isinstance(x, ast.FunctionDef) and x.name == 'get_resample_params')
exec(compile(ast.Module(body=[node], type_ignores=[]), str(df_path), 'exec'), df_scope)
params = df_scope['get_resample_params']('sinc_fast')
assert params == dict(resampling_method='sinc_interpolation', lowpass_filter_width=16)
kernels = {}
for name, dtype in [('double', torch.float64), ('float', torch.float32)]:
    kernel, width = scope['_get_sinc_resample_kernel'](24000, 48000, 24000, dtype=dtype, **params)
    assert list(kernel.shape) == [2, 1, 35] and width == 17
    kernels[name] = kernel.flatten().tolist()
cases = []
for name, length in [('multitone', 2049), ('impulse', 67), ('ramp', 1377)]:
    t = torch.arange(length, dtype=torch.float64)
    audio = .23 * torch.sin(t * .17) + .11 * torch.cos(t * 2.13)
    if name == 'impulse':
        audio.zero_(); audio[0] = 1; audio[33] = -.7; audio[-1] = .5
    if name == 'ramp': audio = torch.linspace(-.2, .3, length, dtype=torch.float64)
    output = scope['resample'](audio, 24000, 48000, **params)
    float_output = scope['resample'](audio.float(), 24000, 48000, **params)
    # Retain the wrong modern Hann result as an explicit negative control.
    hann = scope['resample'](audio, 24000, 48000, lowpass_filter_width=16)
    cases.append(dict(name=name, audio=audio.tolist(), output=output.tolist(), float_output=float_output.tolist(),
                      wrong_hann_error=(output-hann).abs().max().item()))
root = Path(__file__).resolve().parents[2]
source_hash = hashlib.sha256(args.torchaudio_source.read_bytes()).hexdigest()
fixture = root / 'tests/AiDotNet.Tests/TextToSpeech/ReferenceData/metavoice_sinc_fast_reference.json'
fixture.write_text(json.dumps(dict(torchaudio_source='https://github.com/pytorch/audio/blob/v2.1.0/torchaudio/functional/functional.py',
    source_sha256=source_hash, torch_runtime=torch.__version__, effective_window='kaiser', beta_tensor_dtype='float32', kernels=kernels, cases=cases),
    separators=(',', ':')), encoding='utf-8')
native = root / 'src/TextToSpeech/VoiceCloning/MetaVoiceSincFastCoefficients.cs'
def array(name, values):
    return '    internal static readonly double[] ' + name + ' =\n    {\n' + '\n'.join(
        '        ' + ', '.join(format(value, '.17g') for value in values[i:i+5]) + ','
        for i in range(0, len(values), 5)) + '\n    };\n'
native.write_text('// Generated by tools/reference-data/metavoice_sinc_fast_reference.py.\n'
    '// Torchaudio v2.1.0 functional.py SHA256 ' + source_hash + '\n'
    '// Effective legacy sinc_interpolation alias: Kaiser, width16, rolloff.99.\n'
    'namespace AiDotNet.TextToSpeech.VoiceCloning;\n\n'
    'internal static class MetaVoiceSincFastCoefficients\n{\n'
    + array('DoublePrecision', kernels['double']) + array('SinglePrecision', kernels['float']) + '}\n', encoding='utf-8')
print(json.dumps(dict(fixture=str(fixture), native=str(native), cases=len(cases),
                      wrong_hann_errors=[case['wrong_hann_error'] for case in cases])))
