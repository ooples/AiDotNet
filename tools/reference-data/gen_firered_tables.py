"""Generates src/TextToSpeech/FrontEnd/FireRedTtsTextData.cs: the release's tables as code points, so no literal is
transcribed by hand (sentencex 0.6.1 terminators and English abbreviations; FireRedTTS's symbol_reduction, kaomoji and
valid-character regexes)."""
import ast
import os
import re
import sys

# Usage: python gen_firered_tables.py <sentencex package dir> <FireRedTTS checkout>; then gen_lingua_scripts.py.
SENTENCEX = sys.argv[1]
FIRERED = os.path.join(sys.argv[2], 'fireredtts', 'modules', 'text_normalizer')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'TextToSpeech', 'FrontEnd', 'FireRedTtsTextData.cs')

sys.path.insert(0, os.path.dirname(SENTENCEX))
from sentencex.terminators import GLOBAL_SENTENCE_TERMINATORS
from sentencex.languages.en import English
from sentencex.base import Language

src = open(os.path.join(FIRERED, 'utils.py'), encoding='utf-8').read()
tree = ast.parse(src)
symbol_reduction = None
for node in tree.body:
    if isinstance(node, ast.Assign) and node.targets[0].id == 'symbol_reduction':
        symbol_reduction = ast.literal_eval(node.value)
regex_src = open(os.path.join(FIRERED, 'regex_common.py'), encoding='utf-8').read()
ns = {}
exec(regex_src, ns)
kaomoji = ns['kaomoji_regex'].pattern
valid = ns['valid_char_regex'].pattern


def cs_string(s):
    """A C# regular string literal with every non-ASCII or special character escaped as \\uXXXX (UTF-16 units)."""
    out = []
    for ch in s:
        cp = ord(ch)
        units = [cp] if cp < 0x10000 else [0xD800 + ((cp - 0x10000) >> 10), 0xDC00 + ((cp - 0x10000) & 0x3FF)]
        for u in units:
            c = chr(u)
            if c == '\\':
                out.append('\\\\')
            elif c == '"':
                out.append('\\"')
            elif 0x20 <= u < 0x7F:
                out.append(c)
            else:
                out.append('\\u%04X' % u)
    return '"' + ''.join(out) + '"'


def python_regex_to_dotnet(pattern):
    # Python re \uXXXX escapes become literal characters; .NET regex understands \uXXXX too, so pass the decoded
    # characters through cs_string (which re-escapes them for C#).
    return re.sub(r'\\u([0-9a-fA-F]{4})', lambda m: chr(int(m.group(1), 16)), pattern)


terminators = sorted({ord(t) for t in GLOBAL_SENTENCE_TERMINATORS})
assert all(len(t) == 1 for t in GLOBAL_SENTENCE_TERMINATORS)
abbreviations = sorted(English.abbreviations)
quote_pairs = list(Language.quote_pairs.items())
exclamations = sorted(Language.EXCLAMATION_WORDS)

lines = []
lines.append('// <auto-generated> by tools/reference-data/gen_firered_tables.py from sentencex 0.6.1 and FireRedTTS\'s')
lines.append('// fireredtts/modules/text_normalizer (utils.py, regex_common.py). Do not edit by hand. </auto-generated>')
lines.append('namespace AiDotNet.TextToSpeech.FrontEnd;')
lines.append('')
lines.append('internal static class FireRedTtsTextData')
lines.append('{')
lines.append('    /// <summary>sentencex\'s <c>GLOBAL_SENTENCE_TERMINATORS</c> as code points.</summary>')
lines.append('    public static readonly int[] SentenceTerminators =')
lines.append('    {')
for i in range(0, len(terminators), 12):
    lines.append('        ' + ', '.join('0x%X' % c for c in terminators[i:i + 12]) + ',')
lines.append('    };')
lines.append('')
lines.append('    /// <summary>sentencex\'s English abbreviations.</summary>')
lines.append('    public static readonly string[] EnglishAbbreviations =')
lines.append('    {')
for i in range(0, len(abbreviations), 10):
    lines.append('        ' + ', '.join(cs_string(a) for a in abbreviations[i:i + 10]) + ',')
lines.append('    };')
lines.append('')
lines.append('    /// <summary>sentencex\'s <c>EXCLAMATION_WORDS</c>.</summary>')
lines.append('    public static readonly string[] ExclamationWords = { ' + ', '.join(cs_string(w) for w in exclamations) + ' };')
lines.append('')
lines.append('    /// <summary>sentencex\'s <c>quote_pairs</c>, in order (left, right).</summary>')
lines.append('    public static readonly string[][] QuotePairs =')
lines.append('    {')
for left, right in quote_pairs:
    lines.append('        new[] { ' + cs_string(left) + ', ' + cs_string(right) + ' },')
lines.append('    };')
lines.append('')
lines.append('    /// <summary>FireRedTTS\'s <c>symbol_reduction</c>, in order (from, to).</summary>')
lines.append('    public static readonly string[][] SymbolReduction =')
lines.append('    {')
for k, v in symbol_reduction.items():
    lines.append('        new[] { ' + cs_string(k) + ', ' + cs_string(v) + ' },')
lines.append('    };')
lines.append('')
lines.append('    /// <summary>FireRedTTS\'s <c>kaomoji_regex</c>.</summary>')
lines.append('    public const string KaomojiPattern = ' + cs_string(python_regex_to_dotnet(kaomoji)) + ';')
lines.append('')
lines.append('    /// <summary>FireRedTTS\'s <c>valid_char_regex</c>.</summary>')
lines.append('    public const string ValidCharPattern = ' + cs_string(python_regex_to_dotnet(valid)) + ';')
lines.append('}')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', OUT, len(terminators), 'terminators', len(abbreviations), 'abbreviations', len(symbol_reduction), 'reductions')
