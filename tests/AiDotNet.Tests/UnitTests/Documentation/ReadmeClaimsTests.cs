using System.Reflection;
using System.Text;
using AiDotNet.Attributes;
using AiDotNet.Enums;
using AiDotNet.Interfaces;
using Xunit;

namespace AiDotNet.Tests.UnitTests.Documentation;

/// <summary>
/// #2393: the README's headline numbers, badges and comparison table are generated from the compiled assemblies,
/// not written by hand. This test renders them and fails when README.md differs. Run it with
/// <c>AIDOTNET_UPDATE_README=1</c> to rewrite the generated block instead.
/// </summary>
/// <remarks>
/// A model is a public, non-abstract type carrying <see cref="ModelDomainAttribute"/>; families are its declared
/// <see cref="ModelDomain"/> and <see cref="ModelCategory"/> values. Counts are floored (to 5 below 100, to 10
/// below 1,000, to 100 above) and shown with "+", so adding one model does not change the README.
/// </remarks>
public class ReadmeClaimsTests
{
    private const string StartMarker = "<!-- readme-claims:start (generated by ReadmeClaimsTests; AIDOTNET_UPDATE_README=1 to refresh) -->";
    private const string EndMarker = "<!-- readme-claims:end -->";

    private static readonly ModelCategory[] NeuralCategories =
    {
        ModelCategory.NeuralNetwork, ModelCategory.ConvolutionalNetwork, ModelCategory.RecurrentNetwork,
        ModelCategory.Transformer, ModelCategory.GAN, ModelCategory.Autoencoder, ModelCategory.GraphNetwork,
    };

    internal static string Floor(int n) => n switch
    {
        < 5 => n.ToString(System.Globalization.CultureInfo.InvariantCulture),
        < 100 => $"{n / 5 * 5}+",
        < 1000 => $"{n / 10 * 10}+",
        _ => $"{n / 100 * 100:N0}+",
    };

    private sealed record Model(Type Type, ModelDomain[] Domains, ModelCategory[] Categories);

    private static List<Model> Models(Assembly assembly) => assembly.GetExportedTypes()
        .Where(t => t.IsClass && !t.IsAbstract)
        .Select(t => new Model(t,
            t.GetCustomAttributes<ModelDomainAttribute>(inherit: false).Select(a => a.Domain).ToArray(),
            t.GetCustomAttributes<ModelCategoryAttribute>(inherit: false).Select(a => a.Category).ToArray()))
        .Where(m => m.Domains.Length > 0)
        .ToList();

    private static int Implementations(Assembly assembly, Type openInterface) => assembly.GetExportedTypes()
        .Count(t => t.IsClass && !t.IsAbstract && t.GetInterfaces()
            .Any(i => i.IsGenericType && i.GetGenericTypeDefinition() == openInterface));

    internal static string Render()
    {
        var core = typeof(AiDotNet.NeuralNetworks.NeuralNetworkBase<>).Assembly;
        var tensors = typeof(AiDotNet.Tensors.Engines.DirectGpu.IDirectGpuBackend).Assembly;
        var models = Models(core);
        int Domain(ModelDomain d) => models.Count(m => m.Domains.Contains(d));
        int Category(ModelCategory c) => models.Count(m => m.Categories.Contains(c));
        int neural = models.Count(m => m.Categories.Any(NeuralCategories.Contains));
        int classical = models.Count(m => m.Domains.Contains(ModelDomain.MachineLearning)
                                          && !m.Categories.Any(NeuralCategories.Contains));
        int publicTypes = core.GetExportedTypes().Length;
        int lora = Implementations(core, typeof(ILoRAAdapter<>));
        int rag = Implementations(core, typeof(IRetriever<>)) + Implementations(core, typeof(IReranker<>))
                  + Implementations(core, typeof(IDocumentStore<>));
        var backends = tensors.GetExportedTypes()
            .Where(t => t.IsClass && !t.IsAbstract && typeof(AiDotNet.Tensors.Engines.DirectGpu.IDirectGpuBackend).IsAssignableFrom(t)
                        && (t.Namespace ?? string.Empty).StartsWith("AiDotNet.Tensors.Engines.DirectGpu.", StringComparison.Ordinal))
            .Select(t => t.Name.EndsWith("Backend", StringComparison.Ordinal) ? t.Name.Substring(0, t.Name.Length - "Backend".Length) : t.Name)
            .Select(n => n switch { "Cuda" => "CUDA", "Hip" => "HIP", "OpenCl" => "OpenCL", "WebGpu" => "WebGPU", _ => n })
            .Distinct().OrderBy(n => n, StringComparer.Ordinal).ToList();

        static string Badge(string label, string value, string color) =>
            $"![{label.Replace('_', ' ')}](https://img.shields.io/badge/{label}-{Uri.EscapeDataString(value).Replace("-", "--")}-{color})";

        var sb = new StringBuilder();
        sb.AppendLine(StartMarker);
        sb.AppendLine();
        sb.AppendLine($"**{Floor(models.Count)} models and {Floor(publicTypes)} public types, counted from the compiled assembly**");
        sb.AppendLine();
        sb.AppendLine(Badge("Models", Floor(models.Count), "blue"));
        sb.AppendLine(Badge("Neural_Networks", Floor(neural), "blue"));
        sb.AppendLine(Badge("Classical_ML", Floor(classical), "green"));
        sb.AppendLine(Badge("Vision", Floor(Domain(ModelDomain.Vision)), "orange"));
        sb.AppendLine(Badge("Audio", Floor(Domain(ModelDomain.Audio)), "purple"));
        sb.AppendLine(Badge("Video", Floor(Domain(ModelDomain.Video)), "red"));
        sb.AppendLine(Badge("RL_Agents", Floor(Category(ModelCategory.ReinforcementLearningAgent)), "yellow"));
        sb.AppendLine(Badge("Diffusion", Floor(Category(ModelCategory.Diffusion)), "pink"));
        sb.AppendLine(Badge("RAG", Floor(rag), "cyan"));
        sb.AppendLine(Badge("LoRA", Floor(lora), "teal"));
        sb.AppendLine(Badge("GPU_backends", backends.Count.ToString(System.Globalization.CultureInfo.InvariantCulture), "00bcd4"));
        sb.AppendLine();
        sb.AppendLine("| Capability | AiDotNet |");
        sb.AppendLine("|---|---|");
        sb.AppendLine($"| Models (all families) | **{Floor(models.Count)}** |");
        sb.AppendLine($"| Neural network architectures | **{Floor(neural)}** |");
        sb.AppendLine($"| Classical ML algorithms | **{Floor(classical)}** |");
        sb.AppendLine($"| Computer vision models | **{Floor(Domain(ModelDomain.Vision))}** |");
        sb.AppendLine($"| Language models | **{Floor(Domain(ModelDomain.Language))}** |");
        sb.AppendLine($"| Audio models | **{Floor(Domain(ModelDomain.Audio))}** |");
        sb.AppendLine($"| Video models | **{Floor(Domain(ModelDomain.Video))}** |");
        sb.AppendLine($"| Time-series models | **{Floor(Domain(ModelDomain.TimeSeries))}** |");
        sb.AppendLine($"| Reinforcement learning agents | **{Floor(Category(ModelCategory.ReinforcementLearningAgent))}** |");
        sb.AppendLine($"| Diffusion models | **{Floor(Category(ModelCategory.Diffusion))}** |");
        sb.AppendLine($"| LoRA adapters | **{Floor(lora)}** |");
        sb.AppendLine($"| RAG retrievers, rerankers and document stores | **{Floor(rag)}** |");
        sb.AppendLine($"| GPU backends | **{string.Join(", ", backends)}** |");
        sb.AppendLine();
        sb.AppendLine("Counts come from the compiled assemblies: a model is a public concrete type with a `[ModelDomain]` attribute, " +
                      "and a family is one of its declared domains or categories, so one model can count in several rows.");
        sb.AppendLine();
        sb.Append(EndMarker);
        return sb.ToString();
    }

    private static string RepositoryFile(string name)
    {
        for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir is not null; dir = dir.Parent)
        {
            if (File.Exists(Path.Combine(dir.FullName, "AiDotNet.sln")))
                return Path.Combine(dir.FullName, name);
        }
        throw new InvalidOperationException("Could not find the repository root (AiDotNet.sln) above the test output directory.");
    }

    [Fact]
    public void Readme_generated_block_matches_the_assemblies()
    {
        string path = RepositoryFile("README.md");
        string raw = File.ReadAllText(path);
        string newline = raw.Contains("\r\n") ? "\r\n" : "\n";
        string readme = raw.Replace("\r\n", "\n");
        int start = readme.IndexOf(StartMarker, StringComparison.Ordinal);
        int end = readme.IndexOf(EndMarker, StringComparison.Ordinal);
        Assert.True(start >= 0 && end > start, "README.md has no readme-claims block.");
        string current = readme.Substring(start, end + EndMarker.Length - start);
        string expected = Render().Replace("\r\n", "\n");

        if (Environment.GetEnvironmentVariable("AIDOTNET_UPDATE_README") == "1" && current != expected)
        {
            File.WriteAllText(path, readme.Replace(current, expected).Replace("\n", newline));
            return;
        }

        Assert.True(current == expected,
            "README.md's generated block is stale. Rerun this test with AIDOTNET_UPDATE_README=1.\nExpected:\n" + expected);
    }

    [Theory]
    [InlineData(3, "3")]
    [InlineData(57, "55+")]
    [InlineData(867, "860+")]
    [InlineData(2157, "2,100+")]
    public void Counts_are_floored(int n, string shown) => Assert.Equal(shown, Floor(n));
}