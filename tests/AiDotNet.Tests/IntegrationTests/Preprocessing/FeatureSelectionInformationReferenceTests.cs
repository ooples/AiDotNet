        AssertClose(new[] { 0.6133767728269911, 1.096128799790213, 0.5594767699669325, 0.5116466415418951, 0.5938891525534353 },
            selector.MIValues);
        Assert.Equal(new[] { 0, 1 }, selector.SelectedIndices);
    }

