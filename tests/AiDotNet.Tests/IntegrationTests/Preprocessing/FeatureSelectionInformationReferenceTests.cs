    [Fact]
    public void CMIMSelector_UsesExactConditionalMutualInformation()
    {
        // Fleuret (2004): score_j = min over selected s of I(X_j; Y | X_s), I(X_j; Y | X_s) = I(X_j, X_s; Y) - I(X_s; Y),
        // with sklearn.metrics.mutual_info_score / ln 2 on the bins floor((x - min) / ((max - min) / 5 + 1e-10)).
        var selector = new CMIMSelector<double>(nFeaturesToSelect: 3, nBins: 5);
        selector.Fit(X(), Y());

        Assert.Equal(new[] { 1, 2, 3 }, selector.SelectedIndices);
        AssertClose(new[] { 0.0, 1.096128799790213, 0.5598787795221154, 0.5746996402331559, 0.0 }, selector.CMIMScores);
    }

    [Fact]
    public void JointMISelector_IncludesConditionalRedundancy()
    {
        // Brown et al. (2012), eq. 14: I(X_k;Y) - 1/|S| sum_j [I(X_k;X_j) - I(X_k;X_j|Y)]
        var selector = new JointMISelector<double>(nFeaturesToSelect: 3, nBins: 5, redundancyPenalty: 1.0);
        selector.Fit(X(), Y());

        Assert.Equal(new[] { 1, 2, 3 }, selector.SelectedIndices);
        AssertClose(new[] { 0.0, 1.096128799790213, 0.7290139657467211, 0.5746996402331558, 0.0 }, selector.JMIScores);
    }

    [Fact]
    public void MutualInformationSelector_UsesHistogramBins()
    {
        // numpy.histogram(x, bins=5) bins; mutual_info_score(xbins, ybins) / ln 2
        var selector = new MutualInformationSelector<double>(nFeaturesToSelect: 2, nBins: 5);
