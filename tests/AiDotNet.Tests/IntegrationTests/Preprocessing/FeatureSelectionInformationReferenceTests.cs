        // ElasticNet(alpha=0.1, l1_ratio=0.5) on X standardized with the population std and an intercept
        var selector = new ElasticNetSelector<double>(nFeaturesToSelect: 2, alpha: 0.1, l1Ratio: 0.5, maxIterations: 100000, tolerance: 1e-12);
        selector.Fit(X(), Y());

        AssertClose(new[] { 0.08046048994583979, 0.500489510804492, 0.4953286872978211, 0.0, 0.3268502390973202 },
            selector.Coefficients, 1e-7);
        Assert.Equal(new[] { 1, 2 }, selector.SelectedIndices);
    }

    [Fact]
    public void MultiLabelReliefF_IsInvariantToFeatureScale()
    {
        // ReliefF differences are divided by the feature range, so rescaling or shifting a feature changes nothing
        var labels = LabelMatrix();
        var scaledValues = (double[,])XValues.Clone();
        for (int i = 0; i < scaledValues.GetLength(0); i++)
        {
            scaledValues[i, 0] = scaledValues[i, 0] * 1000 + 5;
            scaledValues[i, 3] = scaledValues[i, 3] * 0.001 - 2;
        }

        var original = new MultiLabelReliefF<double>(nFeaturesToSelect: 2, nNeighbors: 3, nIterations: 20, randomState: 11);
        original.Fit(X(), labels);
        var rescaled = new MultiLabelReliefF<double>(nFeaturesToSelect: 2, nNeighbors: 3, nIterations: 20, randomState: 11);
        rescaled.Fit(new Matrix<double>(scaledValues), labels);

        Assert.NotNull(original.FeatureWeights);
        AssertClose(original.FeatureWeights.ToArray(), rescaled.FeatureWeights, 1e-9);
        Assert.Equal(original.SelectedIndices, rescaled.SelectedIndices);
    }
