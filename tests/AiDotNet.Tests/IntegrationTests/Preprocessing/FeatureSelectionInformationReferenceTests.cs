    [Fact]
    public void AlphaInvesting_UsesPearsonPValuesAndFosterStineWealth()
    {
        // p = scipy.stats.pearsonr(x, y).pvalue; alpha = eta w / (1 + eta w); a rejected test earns omega,
        // a failed test pays alpha / (1 - alpha) (Foster & Stine 2008)
        var selector = new AlphaInvesting<double>(nFeaturesToSelect: 10, initialWealth: 0.5, omega: 0.05, eta: 0.25);
        selector.Fit(X(), Y());

        var expectedP = new[] { 2.7093671691451544e-06, 4.3572276921589166e-12, 5.530050881142512e-07, 0.08183373843174238, 0.0003402083221234729 };
        var pValues = selector.PValues;
        Assert.NotNull(pValues);
        for (int j = 0; j < expectedP.Length; j++)
            Assert.True(Math.Abs(expectedP[j] - pValues[j]) <= 1e-8 * expectedP[j], $"p-value {j}: expected {expectedP[j]}, got {pValues[j]}.");

        AssertClose(new[] { 0.13043478260869568, 0.1111111111111111, 0.1208791208791209, 0.14893617021276598, 0.13978494623655915 },
            selector.TestAlphas);
        Assert.Equal(new[] { 0, 1, 2, 3, 4 }, selector.SelectedIndices);
    }

    [Fact]
    public void ClassWeightedFS_BalancedWeightsFollowSortedLabels()
    {
        // sklearn.utils.class_weight.compute_class_weight("balanced", classes=np.unique(y), y=y) with labels -1 / 1
        var labels = new double[40];
        for (int i = 0; i < 40; i++)
            labels[i] = i < 30 ? -1 : 1;
        var selector = new ClassWeightedFS<double>(nFeaturesToSelect: 2, weightingStrategy: ClassWeightingStrategy.Balanced);
        selector.Fit(X(), new Vector<double>(labels));

        AssertClose(new[] { 0.6666666666666666, 2.0 }, selector.ClassWeights);
    }

    [Fact]
    public void FederatedFSSelector_MedianAveragesTheMiddleClients()
    {
        // numpy.median over 4 clients (rows 0-9, 10-19, 20-29, 30-39) of |pearson r| per feature
        var selector = new FederatedFSSelector<double>(nFeaturesToSelect: 2, nClients: 4, aggregationMethod: FederatedScoreAggregation.Median);
        selector.Fit(X(), Y());

        AssertClose(new[] { 0.6889829865241072, 0.8656874911799222, 0.7331693260520947, 0.2842318462343951, 0.6212598105116611 },
            selector.AggregatedScores);
    }

    [Fact]
    public void FisherReliefHybrid_ReliefFollowsKononenko()
    {
        // ReliefF (Kononenko 1994): range-scaled differences, Manhattan neighbours, k = 3 hits and k misses per
        // class weighted by P(C) / (1 - P(class)), m = 40 evenly spaced instances
        var selector = new FisherReliefHybrid<double>(nFeaturesToSelect: 2, fisherWeight: 0.5, nNeighbors: 3);
        selector.Fit(X(), Classes());

        AssertClose(new[] { 0.020567433322535356, 0.07397780925401322, 0.1467818333797715, 0.03815359477124183, 0.034101693677909176 },
            selector.ReliefScores);
    }

    [Fact]
    public void FilterWrapper_BackwardEliminationKeepsTheBestFilterScores()
    {
        // The 4 filter candidates by |pearson r| are 1, 2, 0, 4; eliminating down to 2 keeps the two best (1, 2).
        // Master threw InvalidOperationException here (it modified the set it was enumerating).
        var selector = new FilterWrapper<double>(nFeaturesToSelect: 2, filterRatio: 2, useForwardSelection: false);
        selector.Fit(X(), Y());

        Assert.Equal(new[] { 1, 2 }, selector.SelectedIndices);
        AssertClose(new[] { 0.6661536050625665, 0.8491839110386675, 0.6980331892068828, 0.2784992795689858, 0.5382620913916011 },
            selector.FilterScores);
    }

