    private static void AssertClose(double[] expected, Vector<double>? actual)
    {
        Assert.NotNull(actual);
        Assert.Equal(expected.Length, actual.Length);
        for (int j = 0; j < expected.Length; j++)
            Assert.True(Math.Abs(expected[j] - actual[j]) <= Tolerance,
                $"Entry {j}: expected {expected[j]}, got {actual[j]}.");
    }

    [Fact]
    public void InformationMic_MatchesMinepy()
    {
        var selector = new InformationMic(nFeaturesToSelect: 3);
        selector.Fit(new Matrix<double>(MicX), new Vector<double>(MicY));

        AssertClose(MicDefault, selector.MICScores);
        Assert.Equal(new[] { 0, 1, 3 }, selector.SelectedIndices);

        var coarse = new InformationMic(nFeaturesToSelect: 2, alpha: 0.5, c: 5);
        coarse.Fit(new Matrix<double>(MicX), new Vector<double>(MicY));

        AssertClose(MicAlphaHalfC5, coarse.MICScores);
        Assert.Equal(new[] { 0, 3 }, coarse.SelectedIndices);
    }

    [Fact]
    public void NonlinearMic_MatchesMinepy()
