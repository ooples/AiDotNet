/// subsets of size 1 to 3 in <c>itertools.combinations</c> order). The OSFS data is generated by:
/// <code>
/// rng = np.random.default_rng(1); n = 60; z = rng.normal(size=(n, 4))
/// X = np.column_stack([z[:,0], z[:,0] + 0.05*z[:,1], z[:,2], z[:,3],
///                      0.6*z[:,0] + 0.3*z[:,2] + 0.4*rng.normal(size=n), rng.normal(size=n)]).round(3)
/// y = (X[:,1] + X[:,3] + 0.5*rng.normal(size=n)).round(3)
/// </code>
/// </para>
/// </remarks>
