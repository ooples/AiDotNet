    [Fact]
    public void Mic_RejectsParametersMinepyRejects()
    {
        // mine_check_parameter: alpha in (0, 1] or alpha >= 4, and c > 0
        Assert.Throws<ArgumentOutOfRangeException>(() => new InformationMic(alpha: 2.0));
        Assert.Throws<ArgumentOutOfRangeException>(() => new NonlinearMic(alpha: 0.0));
        Assert.Throws<ArgumentOutOfRangeException>(() => new NonparametricMic(c: 0.0));
    }

    [Fact]
    public void OSFS_FollowsRelevanceThenRedundancyAnalysis()
    {
        // Feature 0 enters first and is dropped once its near copy (1), which builds y, arrives; 4 and 2 are
        // relevant on their own but independent of y given 1; 5 is never relevant.
        var selector = new OSFS<double>(nFeaturesToSelect: 10, alpha: 0.05, maxConditioningSetSize: 3);
        selector.Fit(new Matrix<double>(OsfsX), new Vector<double>(OsfsY));

        Assert.Equal(new[] { 1, 3 }, selector.SelectedIndices);
        AssertClose(
            new[] { 0.64070801867746419, 0.6390609560189412, 0.30181788802471926, 0.62221373561373539, 0.42766470871666845, 0.11917557439904219 },
            selector.FeatureScores);
    }

    [Fact]
    public void OSFS_CapsTheCandidateSetByCorrelation()
    {
        // BCF is {1, 3}; with room for one feature the one more correlated with y (1) stays
        var selector = new OSFS<double>(nFeaturesToSelect: 1);
        selector.Fit(new Matrix<double>(OsfsX), new Vector<double>(OsfsY));

        Assert.Equal(new[] { 1 }, selector.SelectedIndices);
    }
