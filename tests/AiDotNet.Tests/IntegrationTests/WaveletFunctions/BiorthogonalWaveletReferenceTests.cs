        var wavelet = new BiorthogonalWavelet<double>(decompositionOrder, reconstructionOrder);
        var filters = PywtFilters[$"{reconstructionOrder}.{decompositionOrder}"];
        var signal = TestSignal(16);

        var (approximation, detail) = wavelet.Decompose(new Vector<double>(signal));

        // a[i] = sum_k dec_lo[k] * x[(2i + L - 1 - k) mod n]: convolution with dec_lo, periodic, downsampled.
        AssertTaps(PeriodicAnalysis(signal, filters[0]), approximation, TransformTolerance);
        AssertTaps(PeriodicAnalysis(signal, filters[1]), detail, TransformTolerance);
    }

