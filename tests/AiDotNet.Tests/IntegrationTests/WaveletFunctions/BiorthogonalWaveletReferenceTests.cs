    private static double[] TestSignal(int length)
    {
        var signal = new double[length];
        for (int i = 0; i < length; i++)
        {
            signal[i] = Math.Cos(0.7 * i) + 0.1 * i + (i % 3 == 0 ? 0.5 : 0.0);
        }

        return signal;
    }

    private static double[] PeriodicAnalysis(double[] signal, double[] taps)
    {
        int n = signal.Length;
        int length = taps.Length;
        var result = new double[n / 2];
        for (int i = 0; i < n / 2; i++)
        {
            double sum = 0.0;
            for (int k = 0; k < length; k++)
            {
                sum += taps[k] * signal[(2 * i + length - 1 - k) % n];
            }

            result[i] = sum;
        }

        return result;
    }

    private static void AssertTaps(double[] expected, Vector<double> actual, double tolerance)
    {
        Assert.Equal(expected.Length, actual.Length);
        for (int i = 0; i < expected.Length; i++)
        {
            Assert.Equal(expected[i], actual[i], tolerance);
        }
    }
