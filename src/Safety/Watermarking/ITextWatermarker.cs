using AiDotNet.Interfaces;

namespace AiDotNet.Safety.Watermarking;

/// <summary>
/// Interface for keyed text watermarkers that detect, and embed, a watermark in text.
/// </summary>
/// <remarks>
/// <para>
/// A text watermark is embedded either while the text is generated, by biasing the language model's next-token
/// logits toward a keyed "green list" (<see cref="IGenerationWatermarker{T}"/>, Kirchenbauer et al. 2023), or after
/// generation, by keyed meaning-preserving substitutions (<see cref="ITextWatermarkEmbedder{T}"/>). Detection is a
/// statistical test with a stated false-positive rate: only a detector holding the same key finds the mark.
/// </para>
/// <para>
/// <b>For Beginners:</b> A text watermarker adds an invisible signature to AI-generated text.
/// Humans can't see the watermark, but a detector with the right key can find it later to show the text was
/// generated by your system.
/// </para>
/// <para>
/// <b>References:</b>
/// - Kirchenbauer et al., A Watermark for Large Language Models (ICML 2023, arxiv:2301.10226)
/// - SoK: Systematization of watermarking across modalities (2024, arxiv:2411.18479)
/// </para>
/// </remarks>
/// <typeparam name="T">The numeric type used for calculations.</typeparam>
public interface ITextWatermarker<T> : ITextSafetyModule<T>
{
    /// <summary>
    /// Detects the watermark confidence score in the given text (0.0 = no watermark, 1.0 = certain).
    /// </summary>
    /// <param name="text">The text to check for a watermark.</param>
    /// <returns>A watermark detection confidence score.</returns>
    double DetectWatermark(string text);

    /// <summary>
    /// Detects the watermark in the given text and reports the test behind the confidence.
    /// </summary>
    /// <param name="text">The text to check for a watermark.</param>
    /// <returns>The detection result, including the z-score and p-value.</returns>
    WatermarkResult Detect(string text);
}
