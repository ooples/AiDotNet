namespace AiDotNet.ComputerVision.Segmentation.Common;

/// <summary>
/// A minimal embedded 5x7 bitmap font, used to draw class labels and scores directly into an image
/// tensor.
/// </summary>
/// <remarks>
/// <para>
/// <b>For Beginners:</b> To write text onto an image you need to know the shape of every letter. A
/// bitmap font stores each character as a tiny grid of on/off dots — here 5 wide and 7 tall — which
/// can be stamped straight into the picture. It is the simplest way to draw text without depending
/// on the operating system's fonts.
/// </para>
/// <para>
/// This exists so <see cref="SegmentationVisualizationConfig.ShowLabels"/> and
/// <see cref="SegmentationVisualizationConfig.ShowScores"/> are honoured rather than rejected. The
/// alternative — depending on a system font stack or an imaging library — would drag a platform
/// dependency into a numerics library for the sake of a debug overlay.
/// </para>
/// <para>
/// <b>Encoding.</b> Covers printable ASCII (0x20-0x7E). Each glyph is 5 bytes, one per column, and
/// within a byte bit 0 is the TOP row through bit 6 the bottom — the long-standing 5x7 LCD font
/// layout. Characters outside the range render as a hollow box so unsupported text is visible rather
/// than silently blank.
/// </para>
/// </remarks>
internal static class BitmapFont5x7
{
    /// <summary>Glyph width in dots.</summary>
    internal const int GlyphWidth = 5;

    /// <summary>Glyph height in dots.</summary>
    internal const int GlyphHeight = 7;

    /// <summary>Blank columns inserted between glyphs.</summary>
    internal const int Advance = 1;

    private const char FirstChar = ' ';   // 0x20
    private const char LastChar = '~';    // 0x7E

