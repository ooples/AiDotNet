    /// <summary>Total width in pixels that <paramref name="text"/> occupies at the given scale.</summary>
    internal static int MeasureWidth(string text, int scale)
    {
        if (string.IsNullOrEmpty(text)) return 0;
        return text.Length * (GlyphWidth + Advance) * scale - Advance * scale;
    }

    /// <summary>Total height in pixels at the given scale.</summary>
    internal static int MeasureHeight(int scale) => GlyphHeight * scale;

    /// <summary>Returns the 5 column masks for a character, falling back to a hollow box.</summary>
    private static ReadOnlySpan<byte> GlyphFor(char c)
    {
        if (c < FirstChar || c > LastChar) return Unknown;
        int offset = (c - FirstChar) * GlyphWidth;
        return new ReadOnlySpan<byte>(Glyphs, offset, GlyphWidth);
    }

    /// <summary>
    /// Stamps <paramref name="text"/> into an RGB image tensor [3, H, W] with its top-left corner at
    /// (<paramref name="originX"/>, <paramref name="originY"/>). Pixels outside the image are clipped.
    /// </summary>
    /// <param name="rgb">Destination image [3, H, W].</param>
    /// <param name="numOps">Numeric operations for <typeparamref name="T"/>.</param>
    /// <param name="text">Text to draw.</param>
    /// <param name="originX">Left edge, in pixels.</param>
    /// <param name="originY">Top edge, in pixels.</param>
    /// <param name="r">Foreground red, already in the image's value range.</param>
    /// <param name="g">Foreground green, already in the image's value range.</param>
    /// <param name="b">Foreground blue, already in the image's value range.</param>
    /// <param name="scale">Integer upscale factor; 1 draws at native 5x7.</param>
    internal static void DrawText<T>(
        Tensor<T> rgb,
        INumericOperations<T> numOps,
        string text,
        int originX,
        int originY,
        double r,
        double g,
        double b,
        int scale = 1)
    {
        if (string.IsNullOrEmpty(text)) return;
        if (scale < 1) scale = 1;

        int height = rgb.Shape[1];
        int width = rgb.Shape[2];
        var red = numOps.FromDouble(r);
        var green = numOps.FromDouble(g);
        var blue = numOps.FromDouble(b);

        int penX = originX;
        foreach (char c in text)
        {
            var glyph = GlyphFor(c);
            for (int col = 0; col < GlyphWidth; col++)
            {
                byte bits = glyph[col];
                for (int row = 0; row < GlyphHeight; row++)
                {
                    if ((bits & (1 << row)) == 0) continue;

                    for (int dy = 0; dy < scale; dy++)
                    {
                        for (int dx = 0; dx < scale; dx++)
                        {
                            int x = penX + col * scale + dx;
                            int y = originY + row * scale + dy;
                            if (x < 0 || x >= width || y < 0 || y >= height) continue;
                            rgb[0, y, x] = red;
                            rgb[1, y, x] = green;
                            rgb[2, y, x] = blue;
                        }
                    }
                }
            }
            penX += (GlyphWidth + Advance) * scale;
        }
    }
