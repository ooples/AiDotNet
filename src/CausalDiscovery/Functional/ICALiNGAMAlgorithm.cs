namespace AiDotNet.CausalDiscovery.Functional;

/// <summary>
/// ICA-LiNGAM — Linear Non-Gaussian Acyclic Model using Independent Component Analysis.
/// </summary>
/// <remarks>
/// <para>
/// ICA-LiNGAM exploits the identifiability of the linear model X = BX + e when the noise e
/// is non-Gaussian. Using ICA (Independent Component Analysis), it recovers the mixing matrix
/// and derives the causal ordering and edge weights.
/// </para>
/// <para>
/// <b>Key insight:</b> In a linear Gaussian model, the causal direction is not identifiable
/// from observational data alone. But with non-Gaussian noise, the ICA decomposition uniquely
/// determines the causal structure — this is the LiNGAM identifiability result.
/// </para>
/// <para>
/// <b>Algorithm:</b>
/// <list type="number">
/// <item>Standardize data to zero mean, unit variance</item>
/// <item>Apply ICA (FastICA) to recover independent components S and mixing matrix A</item>
/// <item>Recover B = I - inv(A) (causal adjacency matrix)</item>
/// <item>Find a permutation that makes B lower-triangular (causal order)</item>
/// <item>Prune small coefficients</item>
/// </list>
/// </para>
/// <para>
/// <b>For Beginners:</b> If you have data generated by a linear causal model with noise
/// that isn't perfectly bell-shaped (non-Gaussian), ICA-LiNGAM can figure out the complete
/// causal structure — not just which edges exist, but which direction they go.
/// </para>
/// <para>
/// Reference: Shimizu et al. (2006), "A Linear Non-Gaussian Acyclic Model for Causal Discovery",
/// Journal of Machine Learning Research.
/// </para>
/// </remarks>
/// <typeparam name="T">The numeric type used for calculations.</typeparam>
[ModelDomain(ModelDomain.MachineLearning)]
[ModelDomain(ModelDomain.Causal)]
[ModelCategory(ModelCategory.CausalModel)]
[ModelCategory(ModelCategory.Statistical)]
[ModelTask(ModelTask.CausalInference)]
[ModelComplexity(ModelComplexity.High)]
[ModelInput(typeof(Matrix<>), typeof(Matrix<>))]
[ResearchPaper("A Linear Non-Gaussian Acyclic Model for Causal Discovery", "https://jmlr.org/papers/v7/shimizu06a.html", Year = 2006, Authors = "Shohei Shimizu, Patrik O. Hoyer, Aapo Hyvarinen, Antti Kerminen")]
public class ICALiNGAMAlgorithm<T> : FunctionalBase<T>
{
    /// <inheritdoc/>
    public override string Name => "ICA-LiNGAM";

    /// <inheritdoc/>
    public override bool SupportsNonlinear => false;

    private double _threshold = 0.1;

    /// <summary>
    /// Initializes ICA-LiNGAM with optional configuration.
    /// </summary>
    public ICALiNGAMAlgorithm(CausalDiscoveryOptions? options = null)
    {
        if (options?.EdgeThreshold.HasValue == true)
        {
            double threshold = options.EdgeThreshold.Value;
            if (double.IsNaN(threshold) || double.IsInfinity(threshold) || threshold < 0)
                throw new ArgumentException("EdgeThreshold must be a non-negative finite value.", nameof(options));
            _threshold = threshold;
        }
    }

    /// <inheritdoc/>
    protected override Matrix<T> DiscoverStructureCore(Matrix<T> data)
    {
        int n = data.Rows;
        int d = data.Columns;

        // n is a divisor in CenterData, WhitenData and FastICA, so too few samples fills the returned
        // adjacency with meaningless numbers instead of returning an empty graph. n == 1 is the worst
        // case and passes a naive n == 0 check: centring one sample gives exactly zero, so the
        // covariance is the zero matrix, every eigenvalue is floored to 1e-12, the whitening scale
        // becomes 1e6, and FastICA runs on an all-zero sample. d < 2 puts the eigen decomposition and
        // the row-assignment step on degenerate matrices.
        //
        // The bound matches the sibling RCDAlgorithm's: d + 3 samples, enough for the covariance to
        // have a chance of being estimable at all. PNLAlgorithm returns an empty matrix for its own
        // degenerate case and RCDAlgorithm throws; returning empty is the quieter of the two and is
        // what this method's callers already handle.
        if (d < 2 || n < d + 3) return new Matrix<T>(d, d);


        var centered = CenterData(data, n, d);
        var (whitened, whiteningMatrix) = WhitenData(centered, n, d);

        // FastICA estimates an orthogonal unmixing matrix in whitened coordinates.
        // Transform it back to the centered observation coordinates: W = Q * V.
        var whitenedUnmixing = FastICA(whitened, n, d);
        var unmixing = whitenedUnmixing.Multiply(whiteningMatrix);

        // ICA determines components only up to row permutation. LiNGAM step 2 solves
        // the linear assignment min sum_i 1 / |W[phi(i), i]|.
        int[] rowForColumn = FindRowPermutation(unmixing, d);

        // LiNGAM steps 3-4: normalize each assigned row to make the diagonal one,
        // then recover the structural coefficient matrix B = I - W'. B[target, source]
        // is converted to the repository's adjacency convention [source, target] below.
        var assigned = Engine.TensorIndexSelect(Tensor<T>.FromMatrix(unmixing),
            new Tensor<int>(rowForColumn, new[] { d }), 0);
        var diagonal = Engine.TensorDiagonal(assigned);
        if (CausalTensorHelpers.AnyBelow(Engine.TensorAbs(diagonal), NumOps.FromDouble(1e-12)))
            return new Matrix<T>(d, d);

        var normalized = Engine.TensorDivide(assigned,
            Engine.TensorBroadcastTo(diagonal.Reshape(new[] { d, 1 }), new[] { d, d }));
        var B = Engine.TensorSubtract(Engine.TensorEye<T>(d), normalized).ToMatrix();

        // LiNGAM step 5 / Algorithms B-C: prune the smallest estimates until B can
        // be simultaneously row/column-permuted to strict lower triangular form.
        var order = FindCausalOrder(B, d);

        // Keep only coefficients allowed by the recovered order. This is the paper's
        // DAG projection, not an arbitrary tie-break: later variables may depend on
        // earlier variables, never the reverse.
        var allowed = new List<int>();
        for (int targetPosition = 1; targetPosition < d; targetPosition++)
            for (int sourcePosition = 0; sourcePosition < targetPosition; sourcePosition++)
                allowed.Add(order[sourcePosition] * d + order[targetPosition]);

        // result[source, target] = B[target, source] where allowed and |B| >= threshold.
        var projected = Tensor<T>.FromMatrix(
            CausalTensorHelpers.KeepPositions(Engine.TensorTranspose(Tensor<T>.FromMatrix(B)), allowed));
        var keep = Engine.TensorGreaterEqual(Engine.TensorAbs(projected),
            Engine.TensorFullLike(projected, NumOps.FromDouble(_threshold)));
        return Engine.TensorWhere(keep, projected, Engine.TensorZerosLike(projected)).ToMatrix();
    }

    private Matrix<T> CenterData(Matrix<T> data, int n, int d)
    {
        return CenterColumns(Tensor<T>.FromMatrix(data)).ToMatrix();
    }

    private (Matrix<T> Whitened, Matrix<T> WhiteningMatrix) WhitenData(Matrix<T> centered, int n, int d)
    {
        // Covariance (1/n) X'X, mirrored from its upper triangle so it is exactly symmetric.
        var x = Tensor<T>.FromMatrix(centered);
        var gram = Engine.TensorMatMul(Engine.TensorTranspose(x), x);
        gram = Engine.TensorAdd(Engine.TensorTriu(gram, 0), Engine.TensorTranspose(Engine.TensorTriu(gram, 1)));
        var covariance = Engine.TensorMultiplyScalar(gram, NumOps.FromDouble(1.0 / n)).ToMatrix();

        // whitening[component, feature] = V[feature, component] / sqrt(max(lambda_component, 1e-12)).
        var eigen = new EigenDecomposition<T>(covariance, EigenAlgorithmType.Jacobi);
        var eigenvalues = Engine.TensorMax(eigen.EigenValues.AsTensor(), NumOps.FromDouble(1e-12));
        var scale = Engine.TensorReciprocal(Engine.TensorSqrt(eigenvalues)).Reshape(new[] { d, 1 });
        var whitening = Engine.TensorMultiply(Engine.TensorTranspose(Tensor<T>.FromMatrix(eigen.EigenVectors)),
            Engine.TensorBroadcastTo(scale, new[] { d, d }));

        var whitened = Engine.TensorMatMul(x, Engine.TensorTranspose(whitening));
        return (whitened.ToMatrix(), whitening.ToMatrix());
    }

    private Matrix<T> FastICA(Matrix<T> data, int n, int d)
    {
        const int DefaultSeed = 42;
        var rng = Tensors.Helpers.RandomHelper.CreateSeededRandom(DefaultSeed);
        var x = Tensor<T>.FromMatrix(data);
        var xt = Engine.TensorTranspose(x);
        T nT = NumOps.FromDouble(n);
        T half = NumOps.FromDouble(0.5);
        T tolerance = NumOps.FromDouble(1e-6);

        // The identity + 0.01 * (u - 0.5) start is overwritten row by row below; it is still drawn so
        // the seeded stream feeding the per-component starts is unchanged.
        _ = Tensor<T>.CreateRandom(rng, d, d);

        // Deflation-based FastICA
        var components = new Tensor<T>[d];
        for (int p = 0; p < d; p++)
        {
            var start = Engine.TensorSubtractScalar(Tensor<T>.CreateRandom(rng, d), half).ToVector();
            VectorHelper.NormalizeInPlace(start);
            var w = start.AsTensor();

            for (int iter = 0; iter < 200; iter++)
            {
                // E{X * g(w^T X)} - E{g'(w^T X)} * w, using g(u) = tanh(u)
                var g = Engine.TensorTanh(Engine.TensorMatMul(x, w.Reshape(new[] { d, 1 })));
                T meanGPrime = Engine.TensorMean(Engine.TensorSubtract(Engine.TensorOnesLike(g), Engine.TensorSquare(g)));
                var wNew = Engine.TensorSubtract(
                    Engine.TensorDivideScalar(Engine.TensorMatMul(xt, g).Reshape(new[] { d }), nT),
                    Engine.TensorMultiplyScalar(w, meanGPrime));

                // Orthogonalize against previous components
                for (int k = 0; k < p; k++)
                {
                    T dot = Engine.TensorSum(Engine.TensorMultiply(wNew, components[k]));
                    wNew = Engine.TensorSubtract(wNew, Engine.TensorMultiplyScalar(components[k], dot));
                }

                var normalized = wNew.ToVector();
                VectorHelper.NormalizeInPlace(normalized);
                wNew = normalized.AsTensor();

                // Check convergence
                var diff = Engine.ReduceSum(Engine.TensorAbs(
                    Engine.TensorSubtract(Engine.TensorAbs(wNew), Engine.TensorAbs(w))), new[] { 0 }, true);
                w = wNew;
                if (CausalTensorHelpers.AnyBelow(diff, tolerance)) break;
            }

            components[p] = w;
        }

        return Engine.TensorStack(components, 0).ToMatrix();
    }

    private int[] FindRowPermutation(Matrix<T> unmixing, int d)
    {
        // Hungarian algorithm for the paper's O(d^3) linear-assignment formulation.
        // Columns are observed variables; each receives exactly one ICA component row.
        var u = new double[d + 1];
        var v = new double[d + 1];
        var p = new int[d + 1];
        var way = new int[d + 1];

        for (int row = 1; row <= d; row++)
        {
            p[0] = row;
            int column0 = 0;
            var minValue = Enumerable.Repeat(double.PositiveInfinity, d + 1).ToArray();
            var used = new bool[d + 1];

            do
            {
                used[column0] = true;
                int row0 = p[column0];
                double delta = double.PositiveInfinity;
                int column1 = 0;
                for (int column = 1; column <= d; column++)
                {
                    if (used[column]) continue;
                    double magnitude = Math.Abs(NumOps.ToDouble(unmixing[row0 - 1, column - 1]));
                    double cost = 1.0 / Math.Max(magnitude, 1e-12);
                    double current = cost - u[row0] - v[column];
                    if (current < minValue[column])
                    {
                        minValue[column] = current;
                        way[column] = column0;
                    }
                    if (minValue[column] < delta)
                    {
                        delta = minValue[column];
                        column1 = column;
                    }
                }

                for (int column = 0; column <= d; column++)
                {
                    if (used[column])
                    {
                        u[p[column]] += delta;
                        v[column] -= delta;
                    }
                    else
                    {
                        minValue[column] -= delta;
                    }
                }
                column0 = column1;
            }
            while (p[column0] != 0);

            do
            {
                int column1 = way[column0];
                p[column0] = p[column1];
                column0 = column1;
            }
            while (column0 != 0);
        }

        var rowForColumn = new int[d];
        for (int column = 1; column <= d; column++) rowForColumn[column - 1] = p[column] - 1;
        return rowForColumn;
    }

    private int[] FindCausalOrder(Matrix<T> B, int d)
    {
        var pruned = new double[d, d];
        var entries = new List<(double Magnitude, int Row, int Column)>(d * d);
        for (int i = 0; i < d; i++)
        {
            for (int j = 0; j < d; j++)
            {
                double value = NumOps.ToDouble(B[i, j]);
                pruned[i, j] = value;
                entries.Add((Math.Abs(value), i, j));
            }
        }

        entries.Sort((left, right) => left.Magnitude.CompareTo(right.Magnitude));
        int initiallyPruned = Math.Min(entries.Count, d * (d + 1) / 2);
        int next = 0;
        for (; next < initiallyPruned; next++)
            pruned[entries[next].Row, entries[next].Column] = 0.0;

        // Zero the smallest-magnitude entries one at a time until what remains admits a causal order.
        while (next < entries.Count)
        {
            int[]? order = TryFindCausalOrder(pruned, d);
            if (order is not null) return order;

            pruned[entries[next].Row, entries[next].Column] = 0.0;
            next++;
        }

        // Exhaustion is a real terminal state, but not a failure: every entry is now zero, and an
        // edgeless matrix has no incoming edge for any variable, so this call returns a complete
        // order. The previous code returned the natural order here instead, which read as a safety
        // net for a case that cannot arise. If it ever does, that is a broken invariant in
        // TryFindCausalOrder, and inventing an order would hide it behind a plausible-looking graph.
        return TryFindCausalOrder(pruned, d)
            ?? throw new InvalidOperationException(
                $"{nameof(FindCausalOrder)}: no causal order was found for an all-zero matrix of "
                + $"{d} variables, which has no edges to order around.");
    }

    private static int[]? TryFindCausalOrder(double[,] B, int d)
    {
        var remaining = new bool[d];
        for (int i = 0; i < remaining.Length; i++)
        {
            remaining[i] = true;
        }
        var order = new int[d];

        for (int position = 0; position < d; position++)
        {
            int source = -1;
            for (int row = 0; row < d && source < 0; row++)
            {
                if (!remaining[row]) continue;
                bool hasIncomingEdge = false;
                for (int column = 0; column < d; column++)
                {
                    if (remaining[column] && Math.Abs(B[row, column]) > 1e-12)
                    {
                        hasIncomingEdge = true;
                        break;
                    }
                }
                if (!hasIncomingEdge) source = row;
            }

            if (source < 0) return null;
            order[position] = source;
            remaining[source] = false;
        }

        return order;
    }
}
