using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Operations;

namespace AiDotNet.Generators;

/// <summary>
/// Flags element-by-element tensor work: a <c>Tensor</c>, <c>Vector</c> or <c>Matrix</c> indexer (ADNELEM001), or a
/// per-element <c>INumericOperations&lt;T&gt;</c> call (ADNELEM002), inside a loop or an iterating lambda.
/// </summary>
/// <remarks>
/// <para>
/// Per-element access through the tensor indexers and generic numeric operations is the slowest way to touch tensor
/// data: every element pays bounds and index validation, a virtual call and, through NumOps, a boxed-free but
/// non-vectorized round trip. Profiles keep finding it on hot paths (FasterRCNN's RoI pooling copied its output
/// element by element; the tied output head and RoIAlign spent their time in scalar paths). This gate makes every new
/// occurrence a build error, so the fix is an engine op or a span loop rather than a later profile.
/// </para>
/// <para>
/// Existing occurrences are counted per member in <c>ElementWiseBaseline.txt</c> (an AdditionalFile, one
/// <c>count&lt;TAB&gt;rule|member</c> line each, regenerated by tools/ElementWise/Update-ElementWiseBaseline.ps1), which
/// may only shrink (ADNELEM003): a member may not gain occurrences, and a member that loses them must lower its count. A member whose
/// scalar access is intended carries <c>[ScalarKernel("reason")]</c>.
/// </para>
/// <para>
/// ADNELEM002 is about arithmetic on the elements of a buffer, so a numeric call counts only when a loop around it
/// touches an element of the numeric type in its own body: an indexer or array element of that type, a
/// <c>foreach</c> variable of that type, a per-item lambda that takes or returns one, or a member of a collection of
/// that type that takes or returns one (<c>list.Add(value)</c>, <c>tensor.GetFlat(i)</c>, <c>enumerator.Current</c>),
/// or a field or property of that type on the item the loop is on (<c>items[i].Score</c>, <c>item.Box.X1</c>, also
/// when the item is the parameter of a per-item lambda). An element fetched through a call counts as well: an
/// accessor that is given a position and returns the element (<c>Get(values, i)</c>, <c>values.ElementAt(i)</c>,
/// <c>wrapper.Get(i)</c>, a local function or local lambda that indexes the buffer), <c>Unsafe.Add</c>, and a
/// pointer (<c>p[i]</c>, <c>*p</c>). The host floating-point types count as the numeric type here, so a loop
/// converting a <c>double[]</c> still counts, and so does a conversion into the numeric type of a value indexed out
/// of an integer buffer (<c>FromDouble(bytes[i])</c>), though not one read from a dictionary of tallies or from a
/// fixed position (<c>shape[0]</c>). Known boundary, not counted: a value computed by a method on the item
/// (<c>item.GetFitness()</c>), a delegate that is not a local initialized with a lambda (a <c>Func&lt;int, T&gt;</c>
/// field or parameter), and an accessor without source that is not handed the buffer. A loop that
/// touches none of these is not a loop over elements: it counts epochs, layers, batches or the terms of a series, and
/// its numeric calls are scalar bookkeeping between whole-tensor operations, which no engine op replaces. An element
/// access inside a nested loop belongs to that nested loop, so the scalar step after an inner element loop is not
/// counted against the outer one.
/// </para>
/// <para>
/// The gate runs on the newest target framework only (the compilation that defines <c>NET10_0_OR_GREATER</c>):
/// <c>#if</c> blocks make the counts differ between frameworks, and one framework is enough to stop a new occurrence.
/// </para>
/// </remarks>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class ElementWiseAnalyzer : DiagnosticAnalyzer
{
    internal static readonly DiagnosticDescriptor IndexerInLoop = new(
        "ADNELEM001", "Per-element tensor indexer inside a loop",
        "'{0}' reads or writes one element of a {1} inside a loop in {2}. Use an engine op or a span over the data, or "
        + "mark the member [ScalarKernel(\"reason\")] if the per-element access is intended.",
        "AiDotNet.Performance", DiagnosticSeverity.Error, isEnabledByDefault: true,
        description: "Element-by-element access through the tensor indexers validates indices and dispatches per "
                     + "element. Existing occurrences are counted in ElementWiseBaseline.txt, which may only shrink.");

    internal static readonly DiagnosticDescriptor NumericOperationInLoop = new(
        "ADNELEM002", "Per-element numeric operation inside a loop",
        "'{0}' applies INumericOperations to one element at a time inside a loop in {1}. Use an engine op, or a span "
        + "loop specialized for the element type, or mark the member [ScalarKernel(\"reason\")].",
        "AiDotNet.Performance", DiagnosticSeverity.Error, isEnabledByDefault: true,
        description: "Generic per-element arithmetic cannot vectorize. Existing occurrences are counted in "
                     + "ElementWiseBaseline.txt, which may only shrink.");

    internal static readonly DiagnosticDescriptor BaselineChanged = new(
        "ADNELEM003", "Element-wise baseline must shrink",
        "{0}",
        "AiDotNet.Performance", DiagnosticSeverity.Error, isEnabledByDefault: true,
        description: "ElementWiseBaseline.txt is an exact, shrink-only inventory of the element-wise occurrences that "
                     + "existed when the gate was introduced.");

    private static readonly ImmutableHashSet<string> TensorTypes = ImmutableHashSet.Create(StringComparer.Ordinal,
        "Tensor", "TensorBase", "Vector", "VectorBase", "Matrix", "MatrixBase");

    // Methods whose lambda argument runs once per element (parallel loops and LINQ).
    private static readonly ImmutableHashSet<string> IteratingMethods = ImmutableHashSet.Create(StringComparer.Ordinal,
        "For", "ForEach", "ParallelFor", "ParallelForOrSerial", "Select", "SelectMany", "Where", "Sum", "Aggregate",
        "Any", "All", "Count", "Max", "Min", "Average", "ToDictionary", "Zip", "ForAll", "OrderBy", "OrderByDescending",
        "TakeWhile", "SkipWhile", "First", "FirstOrDefault", "Last", "LastOrDefault", "GroupBy");

    /// <inheritdoc/>
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics =>
        ImmutableArray.Create(IndexerInLoop, NumericOperationInLoop, BaselineChanged);

    /// <inheritdoc/>
    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(start =>
        {
            var firstTree = start.Compilation.SyntaxTrees.FirstOrDefault();
            if (firstTree is null || !firstTree.Options.PreprocessorSymbolNames.Contains("NET10_0_OR_GREATER")) return;
            // Only a project that sets ElementWiseGate is gated. The test project loads this analyzer too, and its loops
            // over tensors build fixtures and check results; they are not hot paths and have no baseline.
            if (!start.Options.AnalyzerConfigOptionsProvider.GlobalOptions.TryGetValue("build_property.ElementWiseGate", out var gate)
                || !string.Equals(gate, "true", StringComparison.OrdinalIgnoreCase)) return;

            var numericOperations = start.Compilation.GetTypeByMetadataName("AiDotNet.Tensors.Interfaces.INumericOperations`1");
            var baseline = LoadBaseline(start.Options, start.CancellationToken);
            var counts = new ConcurrentDictionary<string, int>(StringComparer.Ordinal);
            var occurrences = new ConcurrentBag<(string Key, Diagnostic Diagnostic)>();

            start.RegisterOperationAction(operation =>
            {
                var reference = (IPropertyReferenceOperation)operation.Operation;
                if (!reference.Property.IsIndexer || !IsTensorType(reference.Property.ContainingType)) return;
                if (!IsInsideLoop(operation.Operation) || IsExempt(operation.ContainingSymbol)) return;
                string member = MemberKey(operation.ContainingSymbol);
                string key = IndexerInLoop.Id + "|" + member;
                counts.AddOrUpdate(key, 1, (_, n) => n + 1);
                occurrences.Add((key, Diagnostic.Create(IndexerInLoop, operation.Operation.Syntax.GetLocation(),
                    Trim(operation.Operation.Syntax.ToString()), reference.Property.ContainingType.Name, member)));
            }, OperationKind.PropertyReference);

            if (numericOperations is not null)
            {
                start.RegisterOperationAction(operation =>
                {
                    var invocation = (IInvocationOperation)operation.Operation;
                    var declaring = invocation.TargetMethod.ContainingType?.OriginalDefinition;
                    if (declaring is null || !IsNumericOperations(declaring, numericOperations)) return;
                    if (!IsInsideLoop(operation.Operation) || IsExempt(operation.ContainingSymbol)) return;
                    var elementType = NumericElementType(invocation.TargetMethod.ContainingType, numericOperations);
                    if (!RunsPerElement(operation.Operation, elementType)) return;
                    string member = MemberKey(operation.ContainingSymbol);
                    string key = NumericOperationInLoop.Id + "|" + member;
                    counts.AddOrUpdate(key, 1, (_, n) => n + 1);
                    occurrences.Add((key, Diagnostic.Create(NumericOperationInLoop, operation.Operation.Syntax.GetLocation(),
                        Trim(operation.Operation.Syntax.ToString()), member)));
                }, OperationKind.Invocation);
            }

            start.RegisterCompilationEndAction(end =>
            {
                // A member over its baseline reports every occurrence, so the new one is among them.
                var over = new HashSet<string>(counts.Where(kv =>
                        !baseline.TryGetValue(kv.Key, out int allowed) || kv.Value > allowed)
                    .Select(kv => kv.Key), StringComparer.Ordinal);
                foreach (var (key, diagnostic) in occurrences)
                    if (over.Contains(key)) end.ReportDiagnostic(diagnostic);

                // ADNELEM003: entries that shrank or vanished must be lowered or removed.
                foreach (var entry in baseline)
                {
                    int now = counts.TryGetValue(entry.Key, out int n) ? n : 0;
                    if (now >= entry.Value) continue;
                    string message = now == 0
                        ? $"ElementWiseBaseline.txt lists '{entry.Key}' ({entry.Value}), which no longer has any; remove its line."
                        : $"ElementWiseBaseline.txt lists '{entry.Key}' at {entry.Value}, which now has {now}; lower it to {now}.";
                    end.ReportDiagnostic(Diagnostic.Create(BaselineChanged, Location.None, message));
                }
            });
        });
    }

    /// <summary>Reads ElementWiseBaseline.txt: one "count TAB rule|member" line per member; '#' starts a comment.</summary>
    private static Dictionary<string, int> LoadBaseline(AnalyzerOptions options, System.Threading.CancellationToken cancellationToken)
    {
        var baseline = new Dictionary<string, int>(StringComparer.Ordinal);
        var file = options.AdditionalFiles.FirstOrDefault(f =>
            string.Equals(System.IO.Path.GetFileName(f.Path), "ElementWiseBaseline.txt", StringComparison.OrdinalIgnoreCase));
        var text = file?.GetText(cancellationToken);
        if (text is null) return baseline;
        foreach (var line in text.Lines)
        {
            string content = line.ToString();
            if (content.Length == 0 || content[0] == '#') continue;
            int tab = content.IndexOf('\t');
            if (tab <= 0 || !int.TryParse(content.Substring(0, tab), out int count)) continue;
            baseline[content.Substring(tab + 1)] = count;
        }

        return baseline;
    }

    private static bool IsTensorType(INamedTypeSymbol? type)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            if (TensorTypes.Contains(current.Name)
                && current.ContainingNamespace?.ToDisplayString() == "AiDotNet.Tensors.LinearAlgebra")
                return true;
        }

        return false;
    }

    private static bool IsNumericOperations(INamedTypeSymbol type, INamedTypeSymbol numericOperations)
        => SymbolEqualityComparer.Default.Equals(type, numericOperations)
           || type.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i.OriginalDefinition, numericOperations));

    private static bool IsInsideLoop(IOperation operation)
    {
        for (var current = operation.Parent; current is not null; current = current.Parent)
        {
            if (IsLoopScope(current)) return true;
        }

        return false;
    }

    /// <summary>A loop statement, or a lambda that a per-element method (Parallel.For, LINQ) runs once per item.</summary>
    private static bool IsLoopScope(IOperation operation)
    {
        if (operation is ILoopOperation) return true;
        if (operation is IAnonymousFunctionOperation or ILocalFunctionOperation)
        {
            var argument = operation.Parent is IDelegateCreationOperation creation ? creation.Parent : operation.Parent;
            if (argument is IArgumentOperation { Parent: IInvocationOperation invocation }
                && IteratingMethods.Contains(invocation.TargetMethod.Name))
                return true;
        }

        return false;
    }

    /// <summary>The T of the <c>INumericOperations&lt;T&gt;</c> a numeric call is made on, when it can be told.</summary>
    private static ITypeSymbol? NumericElementType(INamedTypeSymbol? type, INamedTypeSymbol numericOperations)
    {
        if (type is null) return null;
        if (SymbolEqualityComparer.Default.Equals(type.OriginalDefinition, numericOperations))
            return type.TypeArguments.Length == 1 ? type.TypeArguments[0] : null;
        var implemented = type.AllInterfaces.FirstOrDefault(i =>
            SymbolEqualityComparer.Default.Equals(i.OriginalDefinition, numericOperations));
        return implemented is { TypeArguments.Length: 1 } ? implemented.TypeArguments[0] : null;
    }

    /// <summary>
    /// Whether a numeric call runs once per element: some loop around it touches an element of the numeric type in
    /// its own body (not only inside a nested loop). An unknown numeric type counts as per-element.
    /// </summary>
    private static bool RunsPerElement(IOperation call, ITypeSymbol? elementType)
    {
        if (elementType is null) return true;
        for (var current = call.Parent; current is not null; current = current.Parent)
        {
            if (IsLoopScope(current) && TouchesElement(current, elementType)) return true;
        }

        return false;
    }

    /// <summary>
    /// A conversion into the numeric type (<c>FromDouble</c> and its siblings) of a value indexed out of an integer
    /// buffer, or of the variable of a <c>foreach</c> over one: pixel bytes, token ids or class labels lifted into
    /// the numeric type one at a time. A dictionary of tallies is not a buffer, and neither is a fixed position
    /// (<c>shape[0]</c>).
    /// </summary>
    private static bool ConvertsIntegerElement(IInvocationOperation call)
    {
        if (!call.TargetMethod.Name.StartsWith("From", StringComparison.Ordinal)) return false;
        var pending = new Stack<IOperation>();
        foreach (var argument in call.Arguments) pending.Push(argument);
        while (pending.Count > 0)
        {
            var operation = pending.Pop();
            switch (operation)
            {
                case IAnonymousFunctionOperation or ILocalFunctionOperation:
                    continue;
                case IArrayElementReferenceOperation element
                    when IsInteger(element.Type) && element.Indices.Any(i => !i.ConstantValue.HasValue):
                    return true;
                case IPropertyReferenceOperation { Property.IsIndexer: true, Instance: { } buffer } indexer
                    when IsInteger(indexer.Type) && IsIntegerBuffer(Unwrap(buffer).Type)
                         && indexer.Arguments.Any(a => !a.Value.ConstantValue.HasValue):
                    return true;
                case ILocalReferenceOperation local when IsInteger(local.Type) && IsIntegerBufferItem(call, local.Local):
                    return true;
            }

            foreach (var child in operation.ChildOperations) pending.Push(child);
        }

        return false;
    }

    /// <summary>Whether a local is the variable of an enclosing <c>foreach</c> over an integer buffer.</summary>
    private static bool IsIntegerBufferItem(IOperation from, ILocalSymbol local)
    {
        for (var current = from.Parent; current is not null; current = current.Parent)
        {
            if (current is IForEachLoopOperation forEach
                && forEach.Locals.Contains(local, SymbolEqualityComparer.Default))
                return IsIntegerBuffer(Unwrap(forEach.Collection).Type);
        }

        return false;
    }

    private static bool IsInteger(ITypeSymbol? type)
        => type is not null && type.SpecialType is SpecialType.System_SByte or SpecialType.System_Byte
               or SpecialType.System_Int16 or SpecialType.System_UInt16 or SpecialType.System_Int32
               or SpecialType.System_UInt32 or SpecialType.System_Int64 or SpecialType.System_UInt64;

    /// <summary>An array, span, memory or list of integers. A dictionary is not one.</summary>
    private static bool IsIntegerBuffer(ITypeSymbol? type)
    {
        switch (type)
        {
            case IArrayTypeSymbol array:
                return IsInteger(array.ElementType);
            case INamedTypeSymbol named:
                if (named.Name is "Span" or "ReadOnlySpan" or "Memory" or "ReadOnlyMemory"
                    && named.TypeArguments.Length == 1 && IsInteger(named.TypeArguments[0]))
                    return true;
                return IsIntegerList(named) || named.AllInterfaces.Any(IsIntegerList);
            default:
                return false;
        }
    }

    private static bool IsIntegerList(INamedTypeSymbol type)
        => type.Name is "IList" or "IReadOnlyList" && type.TypeArguments.Length == 1 && IsInteger(type.TypeArguments[0]);

    private static IOperation Unwrap(IOperation operation)
    {
        while (operation is IConversionOperation conversion) operation = conversion.Operand;
        return operation;
    }

    /// <summary>Whether a loop scope reads or writes an element of the numeric type outside its nested loops.</summary>
    private static bool TouchesElement(IOperation scope, ITypeSymbol elementType)
    {
        switch (scope)
        {
            case IForEachLoopOperation forEach when forEach.Locals.Any(l => HoldsElement(l.Type, elementType)):
                return true;
            case IAnonymousFunctionOperation lambda when TakesOrMakesElement(lambda.Symbol, elementType):
                return true;
            case ILocalFunctionOperation local when TakesOrMakesElement(local.Symbol, elementType):
                return true;
        }

        var pending = new Stack<IOperation>();
        foreach (var child in scope.ChildOperations) pending.Push(child);
        while (pending.Count > 0)
        {
            var operation = pending.Pop();
            if (IsLoopScope(operation)) continue;
            if (IsElementAccess(operation, elementType) || IsItemMember(operation, scope, elementType)) return true;
            if (operation is IInvocationOperation lifted && HoldsElement(lifted.Type, elementType)
                && ConvertsIntegerElement(lifted))
                return true;
            foreach (var child in operation.ChildOperations) pending.Push(child);
        }

        return false;
    }

    private static bool IsElementAccess(IOperation operation, ITypeSymbol elementType)
    {
        switch (operation)
        {
            case IArrayElementReferenceOperation element:
                return HoldsElement(element.Type, elementType);
            case IPropertyReferenceOperation { Property.IsIndexer: true } indexer:
                return HoldsElement(indexer.Type, elementType);
            case IPropertyReferenceOperation { Instance: { } receiver } property:
                return Same(property.Type, elementType) && IsElementCollection(receiver.Type, elementType);
            case IInvocationOperation invocation:
                return IsElementCall(invocation, elementType);
            default:
                // p[i] and *p on a pointer have no public operation of their own.
                return operation.Kind == OperationKind.None
                       && (operation.Syntax is ElementAccessExpressionSyntax
                           || operation.Syntax.IsKind(SyntaxKind.PointerIndirectionExpression))
                       && HoldsElement(operation.Type ?? operation.SemanticModel?.GetTypeInfo(operation.Syntax).Type, elementType);
        }
    }

    /// <summary>
    /// A call that reads or writes one element:
    /// <list type="bullet">
    /// <item>a member of a collection of the numeric type that takes or returns one (<c>list.Add(value)</c>,
    /// <c>tensor.GetFlat(i)</c>);</item>
    /// <item><c>Unsafe.Add(ref first, i)</c> and its siblings stepping a reference to the numeric type;</item>
    /// <item>a call that is given a position and returns the numeric type, when it is an accessor: for a method,
    /// local function or local lambda with source, a value it returns is an indexed element or a conversion of one
    /// (<c>T Get(T[] a, int i) =&gt; a[i]</c>, <c>wrapper.Get(i)</c>, <c>T At(int i) =&gt; values[i]</c>,
    /// <c>return NumOps.ToDouble(tensor[c, y, x]);</c>); for a method
    /// without source, it is also handed a collection of the numeric type (<c>values.ElementAt(i)</c>).</item>
    /// </list>
    /// A whole-buffer reduction (<c>engine.DotProduct(a, b)</c>) takes no position, and a method with source that
    /// computes its result (<c>schedule.Rate(epoch)</c>) is not an accessor. A delegate that is not a local
    /// initialized with a lambda cannot be read and is not counted.
    /// </summary>
    private static bool IsElementCall(IInvocationOperation invocation, ITypeSymbol elementType)
    {
        var method = invocation.TargetMethod;
        if (invocation.Instance is { } receiver && IsElementCollection(receiver.Type, elementType)
            && (Same(method.ReturnType, elementType) || method.Parameters.Any(p => Same(p.Type, elementType))))
            return true;

        if (!HoldsElement(method.ReturnType, elementType)) return false;
        if (method.ContainingType is { Name: "Unsafe" }
            && method.Name is "Add" or "Subtract" or "AddByteOffset" or "SubtractByteOffset")
            return true;
        if (!invocation.Arguments.Any(a => IsPosition(Unwrap(a.Value).Type))) return false;

        if (method.MethodKind == MethodKind.DelegateInvoke)
        {
            return invocation.Instance is { } target && Unwrap(target) is ILocalReferenceOperation local
                   && local.Local.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax() is VariableDeclaratorSyntax
                   {
                       Initializer.Value: AnonymousFunctionExpressionSyntax lambda
                   }
                   && ReturnsAnElement(lambda.Body);
        }

        var declaration = (method.ReducedFrom ?? method).OriginalDefinition.DeclaringSyntaxReferences
            .Select(r => r.GetSyntax())
            .FirstOrDefault(n => n is BaseMethodDeclarationSyntax or LocalFunctionStatementSyntax);
        switch (declaration)
        {
            case BaseMethodDeclarationSyntax declared:
                return ReturnsAnElement((SyntaxNode?)declared.ExpressionBody?.Expression ?? declared.Body);
            case LocalFunctionStatementSyntax localFunction:
                return ReturnsAnElement((SyntaxNode?)localFunction.ExpressionBody?.Expression ?? localFunction.Body);
            default:
                return invocation.Arguments.Any(a => IsElementCollection(Unwrap(a.Value).Type, elementType));
        }
    }

    private static bool IsPosition(ITypeSymbol? type)
        => IsInteger(type) || type is { Name: "Index", ContainingNamespace.Name: "System" };

    /// <summary>Whether a body returns an indexed element, or a conversion of one, on some path.</summary>
    private static bool ReturnsAnElement(SyntaxNode? body)
    {
        switch (body)
        {
            case ExpressionSyntax expression:
                return IsElementExpression(expression);
            case BlockSyntax block:
                var returns = block.DescendantNodes(n => n is not (AnonymousFunctionExpressionSyntax or LocalFunctionStatementSyntax))
                    .OfType<ReturnStatementSyntax>().ToList();
                return returns.Any(r => r.Expression is not null && IsElementExpression(r.Expression));
            default:
                return false;
        }
    }

    private static bool IsElementExpression(ExpressionSyntax expression)
    {
        while (true)
        {
            switch (expression)
            {
                case ParenthesizedExpressionSyntax parenthesized:
                    expression = parenthesized.Expression;
                    continue;
                case CastExpressionSyntax cast:
                    expression = cast.Expression;
                    continue;
                case RefExpressionSyntax reference:
                    expression = reference.Expression;
                    continue;
                case ElementAccessExpressionSyntax:
                    return true;
                case InvocationExpressionSyntax { ArgumentList.Arguments: { Count: 1 } arguments }:
                    // A conversion of the element: NumOps.ToDouble(tensor[i]), Convert.ToDouble(a[i])
                    expression = arguments[0].Expression;
                    continue;
                case MemberAccessExpressionSyntax member:
                    // A member of the element: items[i].Score
                    expression = member.Expression;
                    continue;
                case PrefixUnaryExpressionSyntax prefix:
                    return prefix.IsKind(SyntaxKind.PointerIndirectionExpression);
                case TupleExpressionSyntax tuple:
                    return tuple.Arguments.Any(a => IsElementExpression(a.Expression));
                default:
                    return false;
            }
        }
    }

    /// <summary>
    /// A field or property of the numeric type read from the item a loop is on: <c>items[i].Value</c>,
    /// <c>item.Value</c> on the variable of the enclosing <c>foreach</c> or on the parameter of the enclosing per-item
    /// lambda, at any depth (<c>item.Box.X1</c>). The values live in objects rather than in one buffer, but the loop
    /// still visits one of them per iteration.
    /// </summary>
    private static bool IsItemMember(IOperation operation, IOperation scope, ITypeSymbol elementType)
    {
        if (operation is not IMemberReferenceOperation { Instance: { } instance } member
            || member is not (IPropertyReferenceOperation or IFieldReferenceOperation)
            || !HoldsElement(member.Type, elementType))
            return false;
        // Walk to the root of the member chain: items[i].Box.X1 is still a value of the item the loop is on.
        while (true)
        {
            if (instance is IConversionOperation conversion) instance = conversion.Operand;
            else if (instance is IMemberReferenceOperation { Instance: { } inner } chain
                     && chain is not IPropertyReferenceOperation { Property.IsIndexer: true }) instance = inner;
            else break;
        }

        return instance switch
        {
            IArrayElementReferenceOperation => true,
            IPropertyReferenceOperation { Property.IsIndexer: true } => true,
            ILocalReferenceOperation local => scope is IForEachLoopOperation forEach
                                              && forEach.Locals.Contains(local.Local, SymbolEqualityComparer.Default),
            IParameterReferenceOperation parameter => scope is IAnonymousFunctionOperation lambda
                                                      && lambda.Symbol.Parameters.Contains(parameter.Parameter, SymbolEqualityComparer.Default),
            _ => false,
        };
    }

    /// <summary>A buffer or sequence of the numeric type: a tensor type, an array, a span or memory, or an enumerable/enumerator of it.</summary>
    private static bool IsElementCollection(ITypeSymbol? type, ITypeSymbol elementType)
    {
        switch (type)
        {
            case null:
                return false;
            case IArrayTypeSymbol array:
                return Same(array.ElementType, elementType);
            case INamedTypeSymbol named:
                if (IsTensorType(named)) return true;
                if (named.Name is "Span" or "ReadOnlySpan" or "Memory" or "ReadOnlyMemory"
                    && named.TypeArguments.Length == 1 && Same(named.TypeArguments[0], elementType))
                    return true;
                return IsSequenceOf(named, elementType) || named.AllInterfaces.Any(i => IsSequenceOf(i, elementType));
            default:
                return false;
        }
    }

    private static bool IsSequenceOf(INamedTypeSymbol type, ITypeSymbol elementType)
        => type.Name is "IEnumerable" or "IEnumerator" && type.TypeArguments.Length == 1
           && Same(type.TypeArguments[0], elementType);

    /// <summary>
    /// A per-item lambda that receives an element, or produces one (a <c>Select</c> that projects anything to the
    /// numeric type builds a buffer of it one element at a time).
    /// </summary>
    private static bool TakesOrMakesElement(IMethodSymbol method, ITypeSymbol elementType)
        => method.Parameters.Any(p => HoldsElement(p.Type, elementType)) || HoldsElement(method.ReturnType, elementType);

    /// <summary>The numeric type itself, or a tuple or key/value pair that carries one.</summary>
    private static bool HoldsElement(ITypeSymbol? type, ITypeSymbol elementType)
    {
        if (Same(type, elementType)) return true;
        return type is INamedTypeSymbol named && (named.IsTupleType || named.Name == "KeyValuePair")
               && named.TypeArguments.Any(a => HoldsElement(a, elementType));
    }

    /// <summary>
    /// The numeric type, or a host floating-point type: a loop that converts a <c>double[]</c> into values of the
    /// numeric type (or back) is a loop over elements as much as one that stays in the numeric type.
    /// </summary>
    private static bool Same(ITypeSymbol? left, ITypeSymbol right)
        => left is not null
           && (SymbolEqualityComparer.Default.Equals(left, right)
               || left.SpecialType is SpecialType.System_Double or SpecialType.System_Single or SpecialType.System_Decimal
               || left is { Name: "Half", ContainingNamespace.Name: "System" });

    private static bool IsExempt(ISymbol? symbol)
    {
        for (var current = symbol; current is not null; current = current.ContainingSymbol)
        {
            if (current.GetAttributes().Any(a => a.AttributeClass?.Name == "ScalarKernelAttribute")) return true;
            if (current is INamespaceSymbol) break;
        }

        return false;
    }

    /// <summary>The baseline key of an occurrence: its outermost containing member, with parameter types.</summary>
    internal static string MemberKey(ISymbol? symbol)
    {
        var member = symbol;
        while (member is IMethodSymbol { MethodKind: MethodKind.LocalFunction or MethodKind.AnonymousFunction or MethodKind.LambdaMethod }
               && member.ContainingSymbol is not null)
            member = member.ContainingSymbol;
        return member?.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat) ?? "?";
    }

    private static string Trim(string text)
    {
        text = text.Replace("\r", " ").Replace("\n", " ");
        return text.Length > 80 ? text.Substring(0, 80) + "..." : text;
    }
