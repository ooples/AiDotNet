using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Operations;

namespace AiDotNet.Generators;

/// <summary>
/// Flags element-by-element tensor work: a <c>Tensor</c>, <c>Vector</c> or <c>Matrix</c> indexer (ADNELEM001), or a
/// per-element <c>INumericOperations&lt;T&gt;</c> call (ADNELEM002), inside a loop or an iterating lambda.
/// </summary>
/// <remarks>
/// <para>
/// Per-element access through the tensor indexers and generic numeric operations is the slowest way to touch tensor
/// data: every element pays bounds and index validation, a virtual call and, through NumOps, a boxed-free but
/// non-vectorized round trip. Profiles keep finding it on hot paths (FasterRCNN's RoI pooling copied its output
/// element by element; the tied output head and RoIAlign spent their time in scalar paths). This gate makes every new
/// occurrence a build error, so the fix is an engine op or a span loop rather than a later profile.
/// </para>
/// <para>
/// Existing occurrences are counted per member in <c>ElementWiseBaseline.txt</c> (an AdditionalFile, one
/// <c>count&lt;TAB&gt;rule|member</c> line each, regenerated by tools/ElementWise/Update-ElementWiseBaseline.ps1), which
/// may only shrink (ADNELEM003): a member may not gain occurrences, and a member that loses them must lower its count. A member whose
/// scalar access is intended carries <c>[ScalarKernel("reason")]</c>.
/// </para>
/// <para>
/// The gate runs on the newest target framework only (the compilation that defines <c>NET10_0_OR_GREATER</c>):
/// <c>#if</c> blocks make the counts differ between frameworks, and one framework is enough to stop a new occurrence.
/// </para>
/// </remarks>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class ElementWiseAnalyzer : DiagnosticAnalyzer
{
    internal static readonly DiagnosticDescriptor IndexerInLoop = new(
        "ADNELEM001", "Per-element tensor indexer inside a loop",
        "'{0}' reads or writes one element of a {1} inside a loop in {2}. Use an engine op or a span over the data, or "
        + "mark the member [ScalarKernel(\"reason\")] if the per-element access is intended.",
        "AiDotNet.Performance", DiagnosticSeverity.Error, isEnabledByDefault: true,
        description: "Element-by-element access through the tensor indexers validates indices and dispatches per "
                     + "element. Existing occurrences are counted in ElementWiseBaseline.txt, which may only shrink.");

    internal static readonly DiagnosticDescriptor NumericOperationInLoop = new(
        "ADNELEM002", "Per-element numeric operation inside a loop",
        "'{0}' applies INumericOperations to one element at a time inside a loop in {1}. Use an engine op, or a span "
        + "loop specialized for the element type, or mark the member [ScalarKernel(\"reason\")].",
        "AiDotNet.Performance", DiagnosticSeverity.Error, isEnabledByDefault: true,
        description: "Generic per-element arithmetic cannot vectorize. Existing occurrences are counted in "
                     + "ElementWiseBaseline.txt, which may only shrink.");

    internal static readonly DiagnosticDescriptor BaselineChanged = new(
        "ADNELEM003", "Element-wise baseline must shrink",
        "{0}",
        "AiDotNet.Performance", DiagnosticSeverity.Error, isEnabledByDefault: true,
        description: "ElementWiseBaseline.txt is an exact, shrink-only inventory of the element-wise occurrences that "
                     + "existed when the gate was introduced.");

    private static readonly ImmutableHashSet<string> TensorTypes = ImmutableHashSet.Create(StringComparer.Ordinal,
        "Tensor", "TensorBase", "Vector", "VectorBase", "Matrix", "MatrixBase");

    // Methods whose lambda argument runs once per element (parallel loops and LINQ).
    private static readonly ImmutableHashSet<string> IteratingMethods = ImmutableHashSet.Create(StringComparer.Ordinal,
        "For", "ForEach", "ParallelFor", "ParallelForOrSerial", "Select", "SelectMany", "Where", "Sum", "Aggregate",
        "Any", "All", "Count", "Max", "Min", "Average", "ToDictionary", "Zip", "ForAll", "OrderBy", "OrderByDescending",
        "TakeWhile", "SkipWhile", "First", "FirstOrDefault", "Last", "LastOrDefault", "GroupBy");

    /// <inheritdoc/>
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics =>
        ImmutableArray.Create(IndexerInLoop, NumericOperationInLoop, BaselineChanged);

    /// <inheritdoc/>
    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(start =>
        {
            var firstTree = start.Compilation.SyntaxTrees.FirstOrDefault();
            if (firstTree is null || !firstTree.Options.PreprocessorSymbolNames.Contains("NET10_0_OR_GREATER")) return;
            // Only a project that sets ElementWiseGate is gated. The test project loads this analyzer too, and its loops
            // over tensors build fixtures and check results; they are not hot paths and have no baseline.
            if (!start.Options.AnalyzerConfigOptionsProvider.GlobalOptions.TryGetValue("build_property.ElementWiseGate", out var gate)
                || !string.Equals(gate, "true", StringComparison.OrdinalIgnoreCase)) return;

            var numericOperations = start.Compilation.GetTypeByMetadataName("AiDotNet.Tensors.Interfaces.INumericOperations`1");
            var baseline = LoadBaseline(start.Options, start.CancellationToken);
            var counts = new ConcurrentDictionary<string, int>(StringComparer.Ordinal);
            var occurrences = new ConcurrentBag<(string Key, Diagnostic Diagnostic)>();

            start.RegisterOperationAction(operation =>
            {
                var reference = (IPropertyReferenceOperation)operation.Operation;
                if (!reference.Property.IsIndexer || !IsTensorType(reference.Property.ContainingType)) return;
                if (!IsInsideLoop(operation.Operation) || IsExempt(operation.ContainingSymbol)) return;
                string member = MemberKey(operation.ContainingSymbol);
                string key = IndexerInLoop.Id + "|" + member;
                counts.AddOrUpdate(key, 1, (_, n) => n + 1);
                occurrences.Add((key, Diagnostic.Create(IndexerInLoop, operation.Operation.Syntax.GetLocation(),
                    Trim(operation.Operation.Syntax.ToString()), reference.Property.ContainingType.Name, member)));
            }, OperationKind.PropertyReference);

            if (numericOperations is not null)
            {
                start.RegisterOperationAction(operation =>
                {
                    var invocation = (IInvocationOperation)operation.Operation;
                    var declaring = invocation.TargetMethod.ContainingType?.OriginalDefinition;
                    if (declaring is null || !IsNumericOperations(declaring, numericOperations)) return;
                    if (!IsInsideLoop(operation.Operation) || IsExempt(operation.ContainingSymbol)) return;
                    string member = MemberKey(operation.ContainingSymbol);
                    string key = NumericOperationInLoop.Id + "|" + member;
                    counts.AddOrUpdate(key, 1, (_, n) => n + 1);
                    occurrences.Add((key, Diagnostic.Create(NumericOperationInLoop, operation.Operation.Syntax.GetLocation(),
                        Trim(operation.Operation.Syntax.ToString()), member)));
                }, OperationKind.Invocation);
            }

            start.RegisterCompilationEndAction(end =>
            {
                // A member over its baseline reports every occurrence, so the new one is among them.
                var over = new HashSet<string>(counts.Where(kv =>
                        !baseline.TryGetValue(kv.Key, out int allowed) || kv.Value > allowed)
                    .Select(kv => kv.Key), StringComparer.Ordinal);
                foreach (var (key, diagnostic) in occurrences)
                    if (over.Contains(key)) end.ReportDiagnostic(diagnostic);

                // ADNELEM003: entries that shrank or vanished must be lowered or removed.
                foreach (var entry in baseline)
                {
                    int now = counts.TryGetValue(entry.Key, out int n) ? n : 0;
                    if (now >= entry.Value) continue;
                    string message = now == 0
                        ? $"ElementWiseBaseline.txt lists '{entry.Key}' ({entry.Value}), which no longer has any; remove its line."
                        : $"ElementWiseBaseline.txt lists '{entry.Key}' at {entry.Value}, which now has {now}; lower it to {now}.";
                    end.ReportDiagnostic(Diagnostic.Create(BaselineChanged, Location.None, message));
                }
            });
        });
    }

    /// <summary>Reads ElementWiseBaseline.txt: one "count TAB rule|member" line per member; '#' starts a comment.</summary>
    private static Dictionary<string, int> LoadBaseline(AnalyzerOptions options, System.Threading.CancellationToken cancellationToken)
    {
        var baseline = new Dictionary<string, int>(StringComparer.Ordinal);
        var file = options.AdditionalFiles.FirstOrDefault(f =>
            string.Equals(System.IO.Path.GetFileName(f.Path), "ElementWiseBaseline.txt", StringComparison.OrdinalIgnoreCase));
        var text = file?.GetText(cancellationToken);
        if (text is null) return baseline;
        foreach (var line in text.Lines)
        {
            string content = line.ToString();
            if (content.Length == 0 || content[0] == '#') continue;
            int tab = content.IndexOf('\t');
            if (tab <= 0 || !int.TryParse(content.Substring(0, tab), out int count)) continue;
            baseline[content.Substring(tab + 1)] = count;
        }

        return baseline;
    }

    private static bool IsTensorType(INamedTypeSymbol? type)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            if (TensorTypes.Contains(current.Name)
                && current.ContainingNamespace?.ToDisplayString() == "AiDotNet.Tensors.LinearAlgebra")
                return true;
        }

        return false;
    }

    private static bool IsNumericOperations(INamedTypeSymbol type, INamedTypeSymbol numericOperations)
        => SymbolEqualityComparer.Default.Equals(type, numericOperations)
           || type.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i.OriginalDefinition, numericOperations));

    private static bool IsInsideLoop(IOperation operation)
    {
        for (var current = operation.Parent; current is not null; current = current.Parent)
        {
            if (current is ILoopOperation) return true;
            if (current is IAnonymousFunctionOperation or ILocalFunctionOperation)
            {
                // A lambda iterates when it is the argument of a per-element method (Parallel.For, LINQ).
                var argument = current.Parent is IDelegateCreationOperation creation ? creation.Parent : current.Parent;
                if (argument is IArgumentOperation { Parent: IInvocationOperation invocation }
                    && IteratingMethods.Contains(invocation.TargetMethod.Name))
                    return true;
            }
        }

        return false;
    }

    private static bool IsExempt(ISymbol? symbol)
    {
        for (var current = symbol; current is not null; current = current.ContainingSymbol)
        {
            if (current.GetAttributes().Any(a => a.AttributeClass?.Name == "ScalarKernelAttribute")) return true;
            if (current is INamespaceSymbol) break;
        }

        return false;
    }

    /// <summary>The baseline key of an occurrence: its outermost containing member, with parameter types.</summary>
    internal static string MemberKey(ISymbol? symbol)
    {
        var member = symbol;
        while (member is IMethodSymbol { MethodKind: MethodKind.LocalFunction or MethodKind.AnonymousFunction or MethodKind.LambdaMethod }
               && member.ContainingSymbol is not null)
            member = member.ContainingSymbol;
        return member?.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat) ?? "?";
    }

    private static string Trim(string text)
    {
        text = text.Replace("\r", " ").Replace("\n", " ");
        return text.Length > 80 ? text.Substring(0, 80) + "..." : text;
    }
}
