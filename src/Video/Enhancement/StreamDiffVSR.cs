/// <summary>
/// Stream-DiffVSR: low-latency streamable video super-resolution by auto-regressive diffusion.
/// </summary>
/// <typeparam name="T">The numeric type used for calculations.</typeparam>
/// <remarks>
/// <para>
/// Stream-DiffVSR (Shiu et al., 2025) upscales a video frame by frame using only the past. Each frame is denoised in four
/// DDIM steps by a UNet distilled from the Stable Diffusion x4 upscaler, which reads the noisy latent next to the LR frame.
/// From the second frame on, the previous HR output is warped to the current frame with RAFT flow (computed on the
/// bicubically upscaled LR frames) and guides the denoiser through a ControlNet (Auto-regressive Temporal Guidance), and
/// the temporal tiny autoencoder's decoder fuses the encoder's features of that warped frame (the Temporal Processor
/// Module).
/// </para>
/// <para>
/// The release trains in three stages: the UNet's rollout distillation, the TPM, then the ARTG module with the UNet, the
/// autoencoder and RAFT frozen. <c>Train</c> runs the last stage as <c>train/train_artg.py</c> does: the previous frame
/// is generated by the four-step UNet alone, decoded, warped and encoded; the current frame's four-step rollout runs with
/// the ControlNet; the loss is the final step's v-prediction MSE plus LPIPS (AlexNet) on the decoded frame, and on every
/// fifth step a PatchGAN discriminator on the frame next to the upscaled LR frame trains and, from the start iteration,
/// adds a non-saturating adversarial term at taming's adaptive weight. The release's discriminator scores the generator's
/// frame in eval mode (running batch-norm statistics); here it always normalizes with the batch's.
/// </para>
/// <para>
/// <b>For Beginners:</b> most video upscalers look at future frames, which adds delay. Stream-DiffVSR only uses frames
/// it has already produced, so it suits live streams and video calls.
/// </para>
/// </remarks>
[ModelDomain(ModelDomain.Video)]
[ModelDomain(ModelDomain.Vision)]
[ModelCategory(ModelCategory.NeuralNetwork)]
[ModelCategory(ModelCategory.Diffusion)]
[ModelTask(ModelTask.Generation)]
[ModelComplexity(ModelComplexity.VeryHigh)]
[ModelInput(typeof(Tensor<>), typeof(Tensor<>))]
[ResearchPaper("Stream-DiffVSR: Low-Latency Streamable Video Super-Resolution via Auto-Regressive Diffusion",
    "https://arxiv.org/abs/2512.23709",
    Year = 2025,
    Authors = "Hau-Shiang Shiu, Chin-Yang Lin, Zhixiang Wang, Chi-Wei Hsiao, Po-Fan Yu, Yu-Chih Chen, Yu-Lun Liu")]
[PaperOptimizer(OptimizerKind.AdamW, LearningRate = 5e-5, Beta1 = 0.9, Beta2 = 0.999, Epsilon = 1e-8, WeightDecay = 1e-2,
                Component = "artg", Schedule = LearningRateSchedulerType.LinearWarmup, WarmupSteps = 1000,
                PostWarmupDecay = LinearWarmupScheduler.DecayMode.Constant,
                Source = "The release (train/train_artg.sh, train_artg.py): AdamW (0.9, 0.999, weight decay 1e-2, eps 1e-8) "
                        + "over the ControlNet at 5e-5, constant after a 1000-step warmup, gradients clipped to norm 1.")]
[PaperOptimizer(OptimizerKind.AdamW, LearningRate = 5e-5, Beta1 = 0.9, Beta2 = 0.999, Epsilon = 1e-8, WeightDecay = 1e-2,
                Component = "discriminator",
                Source = "The release: the same AdamW, without a schedule, for the PatchGAN discriminator.")]
