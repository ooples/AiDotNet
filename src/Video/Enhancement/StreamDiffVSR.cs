    private Tensor<T> Mean(Tensor<T> x) => Engine.ReduceMean(x, Enumerable.Range(0, x.Rank).ToArray(), false);

    /// <summary>One ARTG training batch: the current frames, their ground truth and everything the previous frames give.</summary>
    private sealed class Batch
    {
        internal Batch(Tensor<T> lq, Tensor<T> upscaled, Tensor<T> truth, Tensor<T> latents, Tensor<T> noise, Tensor<T> condition,
            List<Tensor<T>> features)
        {
            Lq = lq;
            Upscaled = upscaled;
            Truth = truth;
            Latents = latents;
            Noise = noise;
            Condition = condition;
            Features = features;
        }

        /// <summary>The current LR frames [B, 3, h, w] in [−1, 1].</summary>
        internal Tensor<T> Lq { get; }

        /// <summary>The current LR frames bicubically upscaled, the discriminator's companion input.</summary>
        internal Tensor<T> Upscaled { get; }

        /// <summary>The current ground truth [B, 3, H, W] in [−1, 1].</summary>
        internal Tensor<T> Truth { get; }

        /// <summary>The ground truth's latents.</summary>
        internal Tensor<T> Latents { get; }

        /// <summary>The noise the rollout starts from.</summary>
        internal Tensor<T> Noise { get; }

        /// <summary>The previous frame's generated x0, decoded and warped to the current frame.</summary>
        internal Tensor<T> Condition { get; }

        /// <summary>The encoder's features of that warped frame, for the decoder's temporal blocks.</summary>
        internal List<Tensor<T>> Features { get; }
    }

    // The release's data step: each clip's middle frame is current and a random neighbour previous; the previous frame is
    // generated by the four-step UNet alone from its ground truth's latents noised to the first timestep, decoded, warped
    // to the current frame with RAFT on the upscaled LR frames, and encoded.
    private Batch Prepare(Tensor<T> input, Tensor<T> target, Random random)
    {
        var low = PreprocessFrames(input);
        var high = NormalizeFrames(target);
        if (low.Rank == 4)
        {
            low = Engine.Reshape(low, new[] { 1 }.Concat(low._shape).ToArray());
            high = Engine.Reshape(high, new[] { 1 }.Concat(high._shape).ToArray());
        }
        int b = low.Shape[0], f = low.Shape[1];
        if (f < 2) throw new ArgumentException("ARTG training needs clips of at least two frames.", nameof(input));
        using var noGrad = new NoGradScope<T>();
        Tensor<T> Frames(Tensor<T> clips, Func<int, int> index, int unit)
        {
            var picked = Enumerable.Range(0, b).Select(i => Engine.Reshape(Engine.TensorNarrow(Engine.TensorNarrow(clips, 0, i, 1), 1, index(i), 1),
                new[] { 1 }.Concat(clips._shape.Skip(2)).ToArray())).ToArray();
            return PadTo(ToSigned(Engine.TensorConcatenate(picked, 0)), unit);
        }
        int middle = f / 2;
        var neighbours = Enumerable.Range(0, b).Select(_ =>
        {
            bool after = middle + 1 < f && (middle == 0 || random.NextDouble() >= 0.5);
            return after ? middle + 1 : middle - 1;
        }).ToArray();
        int unit = Unit, s = _options.ScaleFactor;
        var lq = Frames(low, _ => middle, unit);
        var lqPrevious = Frames(low, i => neighbours[i], unit);
        var truth = Frames(high, _ => middle, unit * s);
        var truthPrevious = Frames(high, i => neighbours[i], unit * s);
        int first = TrailingTimesteps(_options.NumTrainTimesteps, _options.SamplingSteps)[0];
        Tensor<T> Noised(Tensor<T> x0, Tensor<T> noise)
            => Engine.TensorAdd(Scaled(x0, Math.Sqrt(_alphasCumprod[first])), Scaled(noise, Math.Sqrt(1.0 - _alphasCumprod[first])));
        var latents = Encoder.Forward(Engine, truth);
        var previousLatents = Encoder.Forward(Engine, truthPrevious);
        var noise = Gaussian(latents.Shape.ToArray(), random);
        var (_, previousOriginal, _) = Rollout(Noised(previousLatents, Gaussian(previousLatents.Shape.ToArray(), random)), lqPrevious, null);
        var upscaled = Upscaled(lq);
        var upscaledPrevious = Upscaled(lqPrevious);
        var flows = Enumerable.Range(0, b).Select(i => Raft.Flow(Engine, Engine.TensorNarrow(upscaled, 0, i, 1),
            Engine.TensorNarrow(upscaledPrevious, 0, i, 1), _options.FlowIterations)).ToArray();
        var condition = StreamDiffVsrOps.FlowWarp(Engine, Decoder.Forward(Engine, previousOriginal), Engine.TensorConcatenate(flows, 0));
        var features = new List<Tensor<T>>();
        Encoder.Forward(Engine, condition, features);
        return new Batch(lq, upscaled, truth, latents, noise, condition, features);
    }

    // The current frame's rollout with the ARTG module from the ground truth's latents noised to the first timestep.
    private (Tensor<T> LastVelocity, Tensor<T> Frame) Generate(Batch batch)
    {
        int first = TrailingTimesteps(_options.NumTrainTimesteps, _options.SamplingSteps)[0];
        var noisy = Engine.TensorAdd(Scaled(batch.Latents, Math.Sqrt(_alphasCumprod[first])), Scaled(batch.Noise, Math.Sqrt(1.0 - _alphasCumprod[first])));
        var (_, original, velocity) = Rollout(noisy, batch.Lq, batch.Condition);
        var frame = Engine.TensorClamp(Decoder.Forward(Engine, original, batch.Features), NumOps.FromDouble(-1.0), NumOps.One);
        return (velocity, frame);
    }

    // The reconstruction loss: the last step's v-prediction against the velocity of the ground truth's latents and the
    // starting noise at the last timestep (as the release computes it), plus LPIPS on the decoded frame.
    private Tensor<T> ReconstructionLoss(Batch batch, Tensor<T> velocity, Tensor<T> frame)
    {
        int last = TrailingTimesteps(_options.NumTrainTimesteps, _options.SamplingSteps)[_options.SamplingSteps - 1];
        double abar = _alphasCumprod[last];
        var target = Engine.TensorSubtract(Scaled(batch.Noise, Math.Sqrt(abar)), Scaled(batch.Latents, Math.Sqrt(1.0 - abar)));
        var loss = Scaled(Mean(Engine.TensorSquare(Engine.TensorSubtract(velocity, target))), _options.LatentMseWeight);
        if (_lpips is not null) loss = Engine.TensorAdd(loss, Scaled(_lpips.Loss(frame, batch.Truth), _options.LpipsWeight));
        return loss;
    }

    private Tensor<T> Critic(Tensor<T> frame, Tensor<T> upscaled)
        => (_discriminator ?? throw NotInitialized()).Forward(Engine.TensorConcatenate(new[] { frame, upscaled }, 1));

    // softplus(−D(G)): the generator's non-saturating term on the frame in [0, 1] next to the upscaled LR frame.
    private Tensor<T> GeneratorGan(Batch batch, Tensor<T> frame) => Mean(Engine.Softplus(Engine.TensorNegate(Critic(ToUnit(frame), batch.Upscaled))));

    // softplus(−D(real)) + softplus(D(fake)), the real frame lightly noised.
    private Tensor<T> DiscriminatorLoss(Batch batch, Tensor<T> real, Tensor<T> fake)
        => Engine.TensorAdd(Mean(Engine.Softplus(Engine.TensorNegate(Critic(real, batch.Upscaled)))), Mean(Engine.Softplus(Critic(fake, batch.Upscaled))));

    // taming's calculate_adaptive_weight at the ControlNet's middle zero convolution: ‖∇ rec‖ / (‖∇ gan‖ + 1e-4), clamped
    // to [0, 1e4], times the adversarial weight; held constant, as its detach makes it.
    private double AdaptiveWeight(Batch batch)
    {
        var last = Control.MidKernel;
        double Norm(Func<Tensor<T>, Tensor<T>, Tensor<T>> loss)
        {
            using var tape = new GradientTape<T>();
            var (velocity, frame) = Generate(batch);
            var grads = tape.ComputeGradients(loss(velocity, frame), new[] { last });
            if (!grads.TryGetValue(last, out var g)) return 0.0;
            double sum = 0;
            for (int i = 0; i < g.Length; i++) sum += NumOps.ToDouble(g[i]) * NumOps.ToDouble(g[i]);
            return Math.Sqrt(sum);
        }
        double reconstruction = Norm((v, frame) => ReconstructionLoss(batch, v, frame));
        double adversarial = Norm((_, frame) => GeneratorGan(batch, frame));
        return Math.Min(Math.Max(reconstruction / (adversarial + 1e-4), 0.0), 1e4) * _options.GanWeight;
    }

    /// <inheritdoc />
    /// <remarks>
    /// The ARTG stage: the ControlNet on the reconstruction loss and, on every <see cref="StreamDiffVSROptions.DiscriminatorInterval"/>-th
    /// step, the discriminator (when its loss exceeds 0.5, as the release gates it) and, from
    /// <see cref="StreamDiffVSROptions.GanStartIteration"/> on, the adversarial term at the adaptive weight times the
    /// adversarial weight (the release applies the weight twice, through the adaptive weight and through adopt_weight).
    /// </remarks>
    protected override IReadOnlyList<TrainingObjective<T>>? DefineTrainingObjectives(Tensor<T> input, Tensor<T> expectedOutput)
    {
        if (_usingCustomLayers || !_useNativeMode) return null;
        int step = _trainingSteps++;
        var random = RandomHelper.CreateSeededRandom(_random.Next());
        var batch = Prepare(input, expectedOutput, random);
        var sources = new[] { input, expectedOutput };
        bool adversarialStep = _discriminator is not null && step % _options.DiscriminatorInterval == 0;
        double weight = adversarialStep && step >= _options.GanStartIteration ? AdaptiveWeight(batch) * _options.GanWeight : 0.0;
        var objectives = new List<TrainingObjective<T>>
        {
            new(sources, _ =>
            {
                var (velocity, frame) = Generate(batch);
                var loss = ReconstructionLoss(batch, velocity, frame);
                return weight > 0 ? Engine.TensorAdd(loss, Scaled(GeneratorGan(batch, frame), weight)) : loss;
            }) { Optimizer = ArtgOptimizer(), Parameters = () => ControlNetParameters },
        };
        if (adversarialStep)
        {
            Tensor<T> fake, real;
            double value;
            using (new NoGradScope<T>())
            {
                fake = ToUnit(Generate(batch).Frame);
                real = Engine.TensorClamp(Engine.TensorAdd(ToUnit(batch.Truth), Scaled(Gaussian(batch.Truth.Shape.ToArray(), random), DiscriminatorNoise)),
                    NumOps.Zero, NumOps.One);
                value = NumOps.ToDouble(DiscriminatorLoss(batch, real, fake)[0]);
            }
            if (value > DiscriminatorThreshold)
                objectives.Add(new TrainingObjective<T>(sources, _ => DiscriminatorLoss(batch, real, fake))
                {
                    Optimizer = DiscriminatorOptimizer(),
                    Parameters = () => DiscriminatorParameters,
                });
        }
        return objectives;
    }

    TrainingObjectiveKind ITrainingObjectiveProvider<T>.TrainingObjectiveKind => TrainingObjectiveKind.DiffusionDenoising;

    Tensor<T> ITrainingObjectiveProvider<T>.ResolveTrainingTarget(Tensor<T> input, Tensor<T> proposedTarget) => proposedTarget;

    /// <inheritdoc />
    /// <remarks>The reconstruction loss of the ARTG stage with every random draw from a fixed seed.</remarks>
    T ITrainingObjectiveProvider<T>.EvaluateTrainingObjective(Tensor<T> input, Tensor<T> target)
    {
        if (_usingCustomLayers || !_useNativeMode)
            using (new NoGradScope<T>())
                return LossFunction.ComputeTapeLoss(Predict(input), target)[0];
        var batch = Prepare(input, target, RandomHelper.CreateSeededRandom(1729));
        using (new NoGradScope<T>())
        {
            var (velocity, frame) = Generate(batch);
            return ReconstructionLoss(batch, velocity, frame)[0];
        }
    }

