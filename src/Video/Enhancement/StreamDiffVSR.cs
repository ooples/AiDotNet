    /// <summary>Creates a Stream-DiffVSR model in ONNX inference mode.</summary>
    public StreamDiffVSR(NeuralNetworkArchitecture<T> architecture, string modelPath, StreamDiffVSROptions? options = null)
        : base(architecture)
    {
        if (string.IsNullOrWhiteSpace(modelPath))
            throw new ArgumentException("Model path cannot be null or empty.", nameof(modelPath));
        _options = options is null ? new StreamDiffVSROptions() : new StreamDiffVSROptions(options);
        Options = _options;
        _useNativeMode = false;
        ScaleFactor = _options.ScaleFactor;
        _random = RandomHelper.CreateSecureRandom();
        _options.ModelPath = modelPath;
        OnnxModel = new OnnxModel<T>(modelPath, _options.OnnxOptions);
        InitializeLayers();
    }

    /// <summary>Creates a Stream-DiffVSR model in native training mode.</summary>
    /// <param name="architecture">The input description.</param>
    /// <param name="options">The configuration; the release's when null.</param>
    /// <param name="optimizer">The ARTG module's optimizer; the release's AdamW when null.</param>
    public StreamDiffVSR(NeuralNetworkArchitecture<T> architecture, StreamDiffVSROptions? options = null,
        IGradientBasedOptimizer<T, Tensor<T>, Tensor<T>>? optimizer = null)
        : base(architecture, new MeanSquaredErrorLoss<T>())
    {
        _optimizer = optimizer;
        _options = options is null ? new StreamDiffVSROptions() : new StreamDiffVSROptions(options);
        Options = _options;
        var o = _options;
        if (o.BlockChannels is not { Length: > 0 } || o.AttentionHeads < 1
            || o.BlockChannels.Any(c => c < 1 || c % 32 != 0 || c % o.AttentionHeads != 0) || o.LayersPerBlock < 1)
            throw new ArgumentOutOfRangeException(nameof(options), "Every UNet width must split into 32 groups and into the heads.");
        if (o.OnlyCrossAttention is null || o.OnlyCrossAttention.Length != o.BlockChannels.Length)
            throw new ArgumentOutOfRangeException(nameof(options), "OnlyCrossAttention needs one entry per UNet level.");
        int Compression(int[]? levels) => levels is { Length: > 0 } ? 1 << (levels.Length - 1) : 0;
        if (o.ScaleFactor < 1 || Compression(o.ConditioningChannels) != o.ScaleFactor || Compression(o.EncoderBlocks) != o.ScaleFactor
            || Compression(o.DecoderBlocks) != o.ScaleFactor || o.ConditioningChannels.Any(c => c < 1)
            || o.EncoderBlocks.Any(b => b < 0) || o.DecoderBlocks.Any(b => b < 0) || o.VaeChannels < 1)
            throw new ArgumentOutOfRangeException(nameof(options),
                "The condition embedding, the encoder and the decoder must each compress by the scale factor.");
        if (o.CrossAttentionDim < 1 || o.PromptLength < 1 || o.NumTrainTimesteps < 2 || o.SamplingSteps < 1
            || o.SamplingSteps > o.NumTrainTimesteps || o.FlowIterations < 1 || o.DiscriminatorInterval < 1)
            throw new ArgumentOutOfRangeException(nameof(options), "The prompt, schedule, sampling and training intervals must be valid.");
        _useNativeMode = true;
        ScaleFactor = o.ScaleFactor;
        _random = o.Seed is int seed ? RandomHelper.CreateSeededRandom(seed) : RandomHelper.CreateSecureRandom();
        InitializeLayers();
    }

    /// <inheritdoc/>
    protected override void RegisterState(AiDotNet.Models.ModelStateRegistry<T> state)
    {
        base.RegisterState(state);
        // The step count gates the discriminator interval and the adversarial start, so a clone continues where it was.
        state.DeclareDoubleVector(nameof(StreamDiffVSR<T>) + ".TrainingSteps", () => new Vector<double>(new double[] { _trainingSteps }),
            restored => _trainingSteps = restored is { Length: > 0 } ? (int)restored[0] : 0);
    }

    /// <inheritdoc/>
    protected override void RegisterComponents()
    {
        base.RegisterComponents();
        if (!_useNativeMode || _usingCustomLayers) return;
        var frozen = AiDotNet.Models.Parameters.ParameterSlotRole.Frozen;
        // The distilled UNet, the temporal autoencoder, RAFT and AlexNet stay as loaded; the ARTG stage trains the
        // ControlNet and the discriminator.
        RegisterParameterComponent("StreamDiffVSR.UNet", _unetGroup, frozen);
        RegisterParameterComponent("StreamDiffVSR.Artg", _controlGroup);
        RegisterParameterComponent("StreamDiffVSR.TemporalVae", _vaeGroup, frozen);
        RegisterParameterComponent("StreamDiffVSR.Raft", _raftGroup, frozen);
        RegisterParameterComponent("StreamDiffVSR.Lpips", _lpips, frozen);
        RegisterParameterComponent("StreamDiffVSR.Discriminator", _discriminator);
    }

    /// <inheritdoc />
    public override Tensor<T> Upscale(Tensor<T> lowResFrames)
    {
        ThrowIfDisposed();
        var preprocessed = PreprocessFrames(lowResFrames);
        var output = IsOnnxMode ? RunOnnxInference(preprocessed) : Forward(preprocessed);
        return PostprocessOutput(output);
    }

    #region Layers and network

    /// <inheritdoc />
    protected override void InitializeLayers()
    {
        if (!_useNativeMode) return;
        if (Architecture.Layers is not null && Architecture.Layers.Count > 0)
        {
            _usingCustomLayers = true;
            Layers.AddRange(Architecture.Layers);
            return;
        }
        var o = _options;
        // The empty prompt's OpenCLIP embedding: a constant the release computes once and never trains.
        _promptLayer = Layers.Count;
        Layers.Add(RealViformerBlocks.Vector<T>(o.PromptLength * o.CrossAttentionDim, 0.0));
        _unet = new StreamDiffVsrUNet<T>(_unetGroup, Latent + 3, Latent, o.BlockChannels, o.LayersPerBlock, o.OnlyCrossAttention,
            o.AttentionHeads, o.CrossAttentionDim);
        _control = new StreamDiffVsrControlNet<T>(_controlGroup, Latent + 3, o.BlockChannels, o.LayersPerBlock, o.OnlyCrossAttention,
            o.AttentionHeads, o.CrossAttentionDim, o.ConditioningChannels);
        _encoder = new StreamDiffVsrTinyEncoder<T>(_vaeGroup, o.VaeChannels, o.EncoderBlocks, Latent);
        _decoder = new StreamDiffVsrTemporalDecoder<T>(_vaeGroup, o.VaeChannels, o.DecoderBlocks, Latent);
        _raft = new MgldRaft<T>(_raftGroup);
        // A zero weight leaves AlexNet or the discriminator out rather than carrying it unused.
        if (o.LpipsWeight > 0) _lpips = new StreamDiffVsrAlexLpips<T>();
        if (o.GanWeight > 0) _discriminator = new MgldDiscriminator<T>(inChannels: 6);
        _alphasCumprod = AlphasCumprod(o);
    }

    /// <inheritdoc />
    protected override void ResolveLazyLayerShapes()
    {
        if (LayerShapesResolved || _usingCustomLayers || !_useNativeMode) return;
        // ControlNetModel.from_unet: the ARTG module's encoder starts as the UNet's.
        Control.DownGroup.SetParameters(UNet.Down.Group.GetParameters());
        MarkLayerShapesResolved();
    }

