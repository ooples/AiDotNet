    #region Pipeline

    // Inference draws its noise from a fixed seed so the same clip always upscales to the same video.
    private Random InferenceRandom() => RandomHelper.CreateSeededRandom(_options.Seed ?? 42);

    private Tensor<T> Gaussian(int[] shape, Random random)
    {
        var t = new Tensor<T>(shape);
        for (int i = 0; i < t.Length; i++)
        {
            double u1 = 1.0 - random.NextDouble(), u2 = random.NextDouble();
            t[i] = NumOps.FromDouble(Math.Sqrt(-2.0 * Math.Log(u1)) * Math.Cos(2.0 * Math.PI * u2));
        }
        return t;
    }

    private Tensor<T> Scaled(Tensor<T> x, double factor) => Engine.TensorMultiplyScalar(x, NumOps.FromDouble(factor));

    private Tensor<T> ToSigned(Tensor<T> x) => Engine.TensorAddScalar(Scaled(x, 2.0), NumOps.FromDouble(-1.0));

    private Tensor<T> ToUnit(Tensor<T> x) => Scaled(Engine.TensorAddScalar(x, NumOps.One), 0.5);

    private Tensor<T> Prompt(int n)
    {
        var prompt = Engine.Reshape(RealViformerBlocks.Read(Layers, _promptLayer), new[] { 1, _options.PromptLength, _options.CrossAttentionDim });
        return Engine.TensorBroadcastTo(prompt, new[] { n, _options.PromptLength, _options.CrossAttentionDim });
    }

    // The LR side the UNet's halvings need.
    private int Unit => 1 << (_options.BlockChannels.Length - 1);

    // Replicate-pads the right and bottom of [N, C, H, W] to multiples of unit.
    private Tensor<T> PadTo(Tensor<T> frames, int unit)
    {
        int h = frames.Shape[2], w = frames.Shape[3];
        int padH = (unit - h % unit) % unit, padW = (unit - w % unit) % unit;
        return padH == 0 && padW == 0 ? frames : Engine.PadNd(frames, new[] { 0, padW, 0, padH }, PadMode.Replicate, NumOps.Zero);
    }

    private Tensor<T> Upscaled(Tensor<T> lq)
        => Engine.Interpolate(lq, new[] { lq.Shape[2] * _options.ScaleFactor, lq.Shape[3] * _options.ScaleFactor }, InterpolateMode.Bicubic, false);

    // The four-step rollout from x_T next to the LR frames, with the ARTG condition when there is one; the last step's
    // v-prediction and x0 come back with the final latents.
    private (Tensor<T> Latents, Tensor<T> Original, Tensor<T> LastVelocity) Rollout(Tensor<T> x, Tensor<T> lq, Tensor<T>? condition)
    {
        var prompt = Prompt(x.Shape[0]);
        Tensor<T> original = x, velocity = x;
        foreach (int t in TrailingTimesteps(_options.NumTrainTimesteps, _options.SamplingSteps))
        {
            var input = Engine.TensorConcatenate(new[] { x, lq }, 1);
            var timesteps = Enumerable.Repeat((double)t, x.Shape[0]).ToArray();
            List<Tensor<T>>? residuals = null;
            Tensor<T>? mid = null;
            if (condition is not null) (residuals, mid) = Control.Forward(Engine, input, timesteps, prompt, condition, _options.ConditioningScale);
            velocity = UNet.Forward(Engine, input, timesteps, prompt, residuals, mid);
            (x, original) = Step(velocity, t, x);
        }
        return (x, original, velocity);
    }

    // One clip [F, 3, h, w] in [0, 1] to [F, 3, s·h, s·w] in [0, 1], frame by frame (the release's pipeline).
    private Tensor<T> RunClip(Tensor<T> frames, Random random)
    {
        int f = frames.Shape[0], h = frames.Shape[2], w = frames.Shape[3], s = _options.ScaleFactor;
        using var noGrad = new NoGradScope<T>();
        var lq = PadTo(ToSigned(frames), Unit);
        var upscaled = Upscaled(lq);
        var outputs = new List<Tensor<T>>();
        Tensor<T>? previous = null;
        for (int k = 0; k < f; k++)
        {
            var current = Engine.TensorNarrow(lq, 0, k, 1);
            Tensor<T>? warped = null;
            List<Tensor<T>>? features = null;
            if (previous is not null)
            {
                var flow = Raft.Flow(Engine, Engine.TensorNarrow(upscaled, 0, k, 1), Engine.TensorNarrow(upscaled, 0, k - 1, 1), _options.FlowIterations);
                warped = StreamDiffVsrOps.FlowWarp(Engine, previous, flow);
                features = new List<Tensor<T>>();
                Encoder.Forward(Engine, warped, features);
            }
            var noise = Gaussian(new[] { 1, Latent, current.Shape[2], current.Shape[3] }, random);
            var (latents, _, _) = Rollout(noise, current, warped);
            previous = Decoder.Forward(Engine, latents, features);
            outputs.Add(Engine.TensorSlice(previous, new[] { 0, 0, 0, 0 }, new[] { 1, 3, h * s, w * s }));
        }
        return Engine.TensorClamp(ToUnit(Engine.TensorConcatenate(outputs.ToArray(), 0)), NumOps.Zero, NumOps.One);
    }

    // [F, 3, h, w] or [B, F, 3, h, w] in [0, 1] to the same layout at the output size.
    private Tensor<T> RunVideo(Tensor<T> frames, Random random)
    {
        if (frames.Rank == 4) return RunClip(frames, random);
        var outputs = new List<Tensor<T>>();
        for (int b = 0; b < frames.Shape[0]; b++)
        {
            var clip = RunClip(Engine.Reshape(Engine.TensorNarrow(frames, 0, b, 1), frames._shape.Skip(1).ToArray()), random);
            outputs.Add(Engine.Reshape(clip, new[] { 1 }.Concat(clip._shape).ToArray()));
        }
        return Engine.TensorConcatenate(outputs.ToArray(), 0);
    }

