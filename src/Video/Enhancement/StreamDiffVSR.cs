    #region Schedule

    /// <summary>ᾱ_t of the scaled-linear schedule: β spaced linearly in √β from √β_start to √β_end.</summary>
    internal static double[] AlphasCumprod(StreamDiffVSROptions options)
    {
        int n = options.NumTrainTimesteps;
        double a = Math.Sqrt(options.BetaStart), b = Math.Sqrt(options.BetaEnd), product = 1.0;
        var cumprod = new double[n];
        for (int i = 0; i < n; i++)
        {
            double root = a + (b - a) * i / (n - 1);
            product *= 1.0 - root * root;
            cumprod[i] = product;
        }
        return cumprod;
    }

    /// <summary>DDIM's trailing timesteps: round(N − i·N/S) − 1 for i below S.</summary>
    internal static int[] TrailingTimesteps(int total, int steps)
        => Enumerable.Range(0, steps).Select(i => (int)Math.Round(total - i * (double)total / steps, MidpointRounding.ToEven) - 1).ToArray();

    // One DDIM step (η = 0) from the v-prediction: x0 = √ᾱ·x − √(1 − ᾱ)·v, ε = √ᾱ·v + √(1 − ᾱ)·x, then
    // x_prev = √ᾱ_prev·x0 + √(1 − ᾱ_prev)·ε at t − N / S, ᾱ_0 standing in past the start (set_alpha_to_one false).
    private (Tensor<T> Previous, Tensor<T> Original) Step(Tensor<T> v, int t, Tensor<T> x)
    {
        int previous = t - _options.NumTrainTimesteps / _options.SamplingSteps;
        double abar = _alphasCumprod[t], abarPrevious = previous >= 0 ? _alphasCumprod[previous] : _alphasCumprod[0];
        var x0 = Engine.TensorSubtract(Scaled(x, Math.Sqrt(abar)), Scaled(v, Math.Sqrt(1.0 - abar)));
        var eps = Engine.TensorAdd(Scaled(v, Math.Sqrt(abar)), Scaled(x, Math.Sqrt(1.0 - abar)));
        return (Engine.TensorAdd(Scaled(x0, Math.Sqrt(abarPrevious)), Scaled(eps, Math.Sqrt(1.0 - abarPrevious))), x0);
    }

