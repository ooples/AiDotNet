using AiDotNet.Attributes;
using AiDotNet.Enums;

namespace AiDotNet.FederatedLearning.ContinualLearning;

/// <summary>
/// Implements FedCIL — federated class-incremental learning with generative replay, model consolidation and
/// consistency enforcement.
/// </summary>
/// <remarks>
/// <para>
/// FedCIL (Qi et al., 2023) gives every client an auxiliary-classifier GAN (ACGAN): a conditional generator
/// G(y, ε) and a discriminator whose shared hidden layer feeds a real/fake head and a class head (the task
/// classifier). Clients train on their current task plus <b>generative replay</b> of earlier classes drawn from
/// the global generator, and add <b>consistency enforcement</b>: λ·KL(p_global(x̃) ‖ p_local(x̃)) on the
/// replayed samples x̃, which keeps the local classifier consistent with the global one on old classes. The
/// server performs <b>model consolidation</b>: it averages the client ACGANs and then fine-tunes the average
/// with ACGAN steps on synthetic data generated by each client generator for that client's label set.
/// </para>
/// <para><b>For Beginners:</b> Instead of storing old data, every participant keeps a small "imagination" model
/// that can redraw examples of classes it has seen. When a new task arrives, clients practise on real new data
/// and on imagined old data (so they do not forget), and the server merges the clients' imagination models
/// into one that knows every client's classes.</para>
/// <para>
/// Network sizes come from the constructor (feature, noise and hidden dimensions), so the models stay small. The
/// <see cref="IFederatedContinualLearningStrategy{T}"/> members describe the classifier parameters only
/// loosely: FedCIL prevents forgetting through replay, so importance is uniform and gradients pass through.
/// </para>
/// <para>Reference: Qi, D., Zhao, H., Li, S. (2023). "Better Generative Replay for Continual Federated
/// Learning." ICLR 2023.</para>
/// </remarks>
/// <typeparam name="T">The numeric type for model parameters.</typeparam>
[ComponentType(ComponentType.FederatedAggregator)]
[PipelineStage(PipelineStage.Training)]
public class FedCILContinualLearning<T> : Infrastructure.FederatedLearningComponentBase<T>, IFederatedContinualLearningStrategy<T>
{
    private readonly int _numClasses;
    private readonly int _featureDim;
    private readonly int _noiseDim;
    private readonly int _hiddenDim;
    private readonly int _batchSize;
    private readonly double _learningRate;
    private readonly double _consistencyWeight;
    private readonly int _consolidationSteps;
    private readonly Random _rng;
    private readonly SortedSet<int> _knownClasses = new();

    /// <summary>
    /// Creates a new FedCIL strategy.
    /// </summary>
    /// <param name="numClasses">Total number of classes C across all tasks.</param>
    /// <param name="featureDim">Dimension D of the (feature-space) samples the ACGAN generates and classifies.</param>
    /// <param name="noiseDim">Dimension of the generator noise ε. Default: 8.</param>
    /// <param name="hiddenDim">Hidden width of the generator and discriminator. Default: 32.</param>
    /// <param name="batchSize">Samples per real, replay and fake batch. Default: 32.</param>
    /// <param name="learningRate">SGD learning rate for both networks. Default: 0.01.</param>
    /// <param name="consistencyWeight">Weight λ of the consistency (KL) term. Default: 1.</param>
    /// <param name="consolidationSteps">Server ACGAN steps on client-generated data per round. Default: 50.</param>
    /// <param name="seed">Random seed for initialization and sampling. Default: 42.</param>
    public FedCILContinualLearning(int numClasses = 10, int featureDim = 32, int noiseDim = 8, int hiddenDim = 32,
        int batchSize = 32, double learningRate = 0.01, double consistencyWeight = 1.0, int consolidationSteps = 50,
        int seed = 42)
    {
        if (numClasses < 2) throw new ArgumentOutOfRangeException(nameof(numClasses), "Need at least two classes.");
        if (featureDim < 1) throw new ArgumentOutOfRangeException(nameof(featureDim), "Feature dimension must be positive.");
        if (noiseDim < 1) throw new ArgumentOutOfRangeException(nameof(noiseDim), "Noise dimension must be positive.");
        if (hiddenDim < 1) throw new ArgumentOutOfRangeException(nameof(hiddenDim), "Hidden dimension must be positive.");
        if (batchSize < 1) throw new ArgumentOutOfRangeException(nameof(batchSize), "Batch size must be positive.");
        if (consistencyWeight < 0) throw new ArgumentOutOfRangeException(nameof(consistencyWeight), "Consistency weight must be non-negative.");
        if (consolidationSteps < 0) throw new ArgumentOutOfRangeException(nameof(consolidationSteps));

        _numClasses = numClasses;
        _featureDim = featureDim;
        _noiseDim = noiseDim;
        _hiddenDim = hiddenDim;
        _batchSize = batchSize;
        _learningRate = learningRate;
        _consistencyWeight = consistencyWeight;
        _consolidationSteps = consolidationSteps;
        _rng = RandomHelper.CreateSeededRandom(seed);
    }

    /// <summary>
    /// Number of parameters of one ACGAN, in the order of <see cref="GetParameters"/>: generator W1 [(C + noise), H],
    /// b1 [H], W2 [H, D], b2 [D]; discriminator Wh [D, H], bh [H], Wadv [H, 1], badv [1], Wcls [H, C], bcls [C].
    /// </summary>
    public int ParameterCount =>
        (_numClasses + _noiseDim) * _hiddenDim + _hiddenDim + _hiddenDim * _featureDim + _featureDim
        + _featureDim * _hiddenDim + _hiddenDim + _hiddenDim + 1 + _hiddenDim * _numClasses + _numClasses;

    /// <summary>Gets the classes the server has consolidated so far.</summary>
    public IReadOnlyCollection<int> KnownClasses => _knownClasses.ToList().AsReadOnly();

    /// <summary>Gets the consistency weight λ.</summary>
    public double ConsistencyWeight => _consistencyWeight;

    /// <summary>
    /// Creates a randomly initialized ACGAN (Xavier-uniform weights, zero biases).
    /// </summary>
    public FedCILGenerativeModel<T> CreateModel()
    {
        int inputDim = _numClasses + _noiseDim;
        return new FedCILGenerativeModel<T>(
            XavierUniform(inputDim, _hiddenDim), new Tensor<T>(new[] { _hiddenDim }),
            XavierUniform(_hiddenDim, _featureDim), new Tensor<T>(new[] { _featureDim }),
            XavierUniform(_featureDim, _hiddenDim), new Tensor<T>(new[] { _hiddenDim }),
            XavierUniform(_hiddenDim, 1), new Tensor<T>(new[] { 1 }),
            XavierUniform(_hiddenDim, _numClasses), new Tensor<T>(new[] { _numClasses }));
    }

    /// <summary>
    /// Creates an ACGAN from a flat parameter vector laid out as described by <see cref="ParameterCount"/>.
    /// </summary>
    public FedCILGenerativeModel<T> CreateModel(Vector<T> parameters)
    {
        Guard.NotNull(parameters);
        if (parameters.Length != ParameterCount)
        {
            throw new ArgumentException($"Expected {ParameterCount} parameters, got {parameters.Length}.", nameof(parameters));
        }

        var flat = parameters.AsTensor();
        int offset = 0;
        Tensor<T> Take(params int[] shape)
        {
            int length = 1;
            foreach (int s in shape)
            {
                length *= s;
            }

            var part = Engine.TensorSlice(flat, new[] { offset }, new[] { length }).Reshape(shape);
            offset += length;
            return part;
        }

        return new FedCILGenerativeModel<T>(
            Take(_numClasses + _noiseDim, _hiddenDim), Take(_hiddenDim), Take(_hiddenDim, _featureDim), Take(_featureDim),
            Take(_featureDim, _hiddenDim), Take(_hiddenDim), Take(_hiddenDim, 1), Take(1),
            Take(_hiddenDim, _numClasses), Take(_numClasses));
    }

    /// <summary>
    /// Flattens an ACGAN into the parameter layout described by <see cref="ParameterCount"/>.
    /// </summary>
    public Vector<T> GetParameters(FedCILGenerativeModel<T> model)
    {
        Guard.NotNull(model);
        var parts = model.AllTensors().Select(t => t.Reshape(new[] { t.Length })).ToArray();
        return Engine.TensorConcatenate(parts, 0).ToVector();
    }

    /// <summary>
    /// Client update for one task: ACGAN training on the task data plus generative replay of
    /// <paramref name="previousClasses"/> from the global generator, with consistency enforcement against the
    /// global classifier on the replayed samples.
    /// </summary>
    /// <param name="globalModel">Current global ACGAN (left unchanged).</param>
    /// <param name="features">Task samples, one row per sample, <c>featureDim</c> columns.</param>
    /// <param name="labels">Class of every row.</param>
    /// <param name="previousClasses">Classes of earlier tasks to replay (may be empty for the first task).</param>
    /// <param name="steps">Number of training steps.</param>
    /// <returns>The trained local ACGAN.</returns>
    public FedCILGenerativeModel<T> TrainClient(FedCILGenerativeModel<T> globalModel, Matrix<T> features, int[] labels,
        IReadOnlyCollection<int> previousClasses, int steps)
    {
        Guard.NotNull(globalModel);
        Guard.NotNull(features);
        Guard.NotNull(labels);
        Guard.NotNull(previousClasses);
        if (features.Rows == 0 || features.Rows != labels.Length || features.Columns != _featureDim)
        {
            throw new ArgumentException(
                $"Features must be a non-empty [n, {_featureDim}] matrix with one label per row.", nameof(features));
        }

        ValidateClasses(labels, nameof(labels));
        ValidateClasses(previousClasses, nameof(previousClasses));

        var local = CreateModel(GetParameters(globalModel));
        var data = Tensor<T>.FromMatrix(features);
        var replayClasses = previousClasses.Distinct().OrderBy(c => c).ToArray();
        var fakeClasses = labels.Concat(replayClasses).Distinct().OrderBy(c => c).ToArray();

        for (int step = 0; step < steps; step++)
        {
            // Real batch (with replacement) from the task data.
            var rows = new int[_batchSize];
            var realY = new int[_batchSize];
            for (int i = 0; i < _batchSize; i++)
            {
                rows[i] = _rng.Next(features.Rows);
                realY[i] = labels[rows[i]];
            }

            var realX = Engine.TensorGather(data, new Tensor<int>(rows, new[] { _batchSize }), 0);
            int replayCount = 0;
            if (replayClasses.Length > 0)
            {
                // Generative replay: old classes drawn from the (frozen) global generator, treated as real data.
                var replayY = SampleFrom(replayClasses, _batchSize);
                var replayX = GeneratorForward(globalModel, replayY, SampleNoise(_batchSize)).Output;
                realX = Engine.TensorConcatenate(new[] { realX, replayX }, 0);
                realY = realY.Concat(replayY).ToArray();
                replayCount = _batchSize;
            }

            TrainStep(local, realX, realY, SampleFrom(fakeClasses, _batchSize), replayCount > 0 ? globalModel : null, replayCount);
        }

        return local;
    }

    /// <summary>
    /// Server model consolidation: weighted average of the client ACGANs, then ACGAN fine-tuning on synthetic data
    /// that each client generator produces for its own label set.
    /// </summary>
    /// <param name="clientModels">Trained client ACGANs.</param>
    /// <param name="clientClasses">Classes each client has learned so far.</param>
    /// <param name="clientWeights">Optional aggregation weights (default 1 per client).</param>
    /// <returns>The consolidated global ACGAN.</returns>
    public FedCILGenerativeModel<T> Consolidate(Dictionary<int, FedCILGenerativeModel<T>> clientModels,
        Dictionary<int, IReadOnlyCollection<int>> clientClasses, Dictionary<int, double>? clientWeights)
    {
        Guard.NotNull(clientModels);
        Guard.NotNull(clientClasses);
        if (clientModels.Count == 0)
            throw new ArgumentException("No client models provided.", nameof(clientModels));

        double totalWeight = clientModels.Keys.Sum(id => clientWeights?.GetValueOrDefault(id, 1.0) ?? 1.0);
        if (totalWeight <= 0)
            throw new ArgumentException("Client weights must sum to a positive value.", nameof(clientWeights));

        var average = new Vector<T>(ParameterCount);
        var sources = new List<(FedCILGenerativeModel<T> Model, int[] Classes)>();
        foreach (var (clientId, model) in clientModels)
        {
            if (!clientClasses.TryGetValue(clientId, out var classes) || classes.Count == 0)
            {
                throw new ArgumentException($"Client {clientId} must report the classes it has learned.", nameof(clientClasses));
            }

            ValidateClasses(classes, nameof(clientClasses));
            double w = clientWeights?.GetValueOrDefault(clientId, 1.0) ?? 1.0;
            average = Engine.Add(average, Engine.Multiply(GetParameters(model), NumOps.FromDouble(w / totalWeight)));
            var ordered = classes.Distinct().OrderBy(c => c).ToArray();
            sources.Add((model, ordered));
            foreach (int c in ordered)
            {
                _knownClasses.Add(c);
            }
        }

        var global = CreateModel(average);
        var allClasses = _knownClasses.ToArray();
        int perClient = Math.Max(1, (_batchSize + sources.Count - 1) / sources.Count);
        for (int step = 0; step < _consolidationSteps; step++)
        {
            var parts = new Tensor<T>[sources.Count];
            var synthY = new List<int>(perClient * sources.Count);
            for (int s = 0; s < sources.Count; s++)
            {
                var y = SampleFrom(sources[s].Classes, perClient);
                parts[s] = GeneratorForward(sources[s].Model, y, SampleNoise(perClient)).Output;
                synthY.AddRange(y);
            }

            TrainStep(global, Engine.TensorConcatenate(parts, 0), synthY.ToArray(), SampleFrom(allClasses, _batchSize), null, 0);
        }

        return global;
    }

    /// <summary>
    /// Draws replay samples of one class from a model's generator.
    /// </summary>
    public Matrix<T> GenerateReplay(FedCILGenerativeModel<T> model, int classLabel, int numSamples)
    {
        Guard.NotNull(model);
        if (classLabel < 0 || classLabel >= _numClasses) throw new ArgumentOutOfRangeException(nameof(classLabel));
        if (numSamples < 1) throw new ArgumentOutOfRangeException(nameof(numSamples), "Number of samples must be positive.");

        var labels = Enumerable.Repeat(classLabel, numSamples).ToArray();
        return GeneratorForward(model, labels, SampleNoise(numSamples)).Output.ToMatrix();
    }

    /// <summary>
    /// Predicts the class of every row with the model's classifier head.
    /// </summary>
    public int[] Classify(FedCILGenerativeModel<T> model, Matrix<T> features)
    {
        Guard.NotNull(model);
        Guard.NotNull(features);
        if (features.Columns != _featureDim)
            throw new ArgumentException($"Features must have {_featureDim} columns.", nameof(features));

        var logits = DiscriminatorForward(model, Tensor<T>.FromMatrix(features)).ClassLogits.Cast<double>().ToArray();
        var predictions = new int[features.Rows];
        for (int i = 0; i < predictions.Length; i++)
        {
            int best = 0;
            for (int c = 1; c < _numClasses; c++)
            {
                if (logits[i * _numClasses + c] > logits[i * _numClasses + best])
                {
                    best = c;
                }
            }

            predictions[i] = best;
        }

        return predictions;
    }

    /// <summary>
    /// Consistency loss: mean over rows of KL(p_global(x) ‖ p_local(x)) between the classifier heads.
    /// </summary>
    public T ComputeConsistencyLoss(FedCILGenerativeModel<T> globalModel, FedCILGenerativeModel<T> localModel, Matrix<T> samples)
    {
        Guard.NotNull(globalModel);
        Guard.NotNull(localModel);
        Guard.NotNull(samples);
        if (samples.Rows == 0) return NumOps.Zero;

        var x = Tensor<T>.FromMatrix(samples);
        var teacherLog = Engine.TensorLogSoftmax(DiscriminatorForward(globalModel, x).ClassLogits, 1);
        var studentLog = Engine.TensorLogSoftmax(DiscriminatorForward(localModel, x).ClassLogits, 1);
        var kl = Engine.TensorMultiply(Engine.TensorExp(teacherLog), Engine.TensorSubtract(teacherLog, studentLog));
        return NumOps.Divide(Engine.TensorSum(kl), NumOps.FromDouble(samples.Rows));
    }

    /// <summary>
    /// One ACGAN step: discriminator update on real (plus replay) and fake samples, with the consistency term on
    /// the replay rows, followed by a generator update against the updated discriminator.
    /// </summary>
    private void TrainStep(FedCILGenerativeModel<T> model, Tensor<T> realX, int[] realY, int[] fakeY,
        FedCILGenerativeModel<T>? teacher, int replayCount)
    {
        int realRows = realY.Length;
        int fakeRows = fakeY.Length;
        int total = realRows + fakeRows;
        var learningRate = NumOps.FromDouble(_learningRate);

        // ---- Discriminator: BCE(adv, real = 1 / fake = 0) + CE(class, label) ----
        var fakeX = GeneratorForward(model, fakeY, SampleNoise(fakeRows)).Output;
        var x = Engine.TensorConcatenate(new[] { realX, fakeX }, 0);
        var advTargets = new int[total];
        for (int i = 0; i < realRows; i++)
        {
            advTargets[i] = 1;
        }

        var (hidden, advLogit, classLogits) = DiscriminatorForward(model, x);
        var inv = NumOps.FromDouble(1.0 / total);
        var gradAdv = Engine.TensorMultiplyScalar(
            Engine.TensorSubtract(Engine.TensorSigmoid(advLogit), new Tensor<int>(advTargets, new[] { total, 1 }).Cast<T>()), inv);
        var studentProbs = Engine.Softmax(classLogits, 1);
        var gradClass = Engine.TensorMultiplyScalar(
            Engine.TensorSubtract(studentProbs, OneHot(realY.Concat(fakeY).ToArray())), inv);

        if (teacher is not null && replayCount > 0 && _consistencyWeight > 0)
        {
            // Consistency enforcement on the replay rows: d/dlogits λ KL(p_t || p_s) = λ (p_s - p_t) / replayCount.
            int start = realRows - replayCount;
            var replayX = Engine.TensorSlice(x, new[] { start, 0 }, new[] { replayCount, _featureDim });
            var teacherProbs = Engine.Softmax(DiscriminatorForward(teacher, replayX).ClassLogits, 1);
            var replayStudent = Engine.TensorSlice(studentProbs, new[] { start, 0 }, new[] { replayCount, _numClasses });
            var consistency = Engine.TensorMultiplyScalar(Engine.TensorSubtract(replayStudent, teacherProbs),
                NumOps.FromDouble(_consistencyWeight / replayCount));
            gradClass = Engine.TensorAdd(gradClass, Engine.TensorConcatenate(new[]
            {
                new Tensor<T>(new[] { start, _numClasses }),
                consistency,
                new Tensor<T>(new[] { fakeRows, _numClasses }),
            }, 0));
        }

        var discGrads = DiscriminatorBackward(model, x, hidden, gradAdv, gradClass);
        model.DiscriminatorHiddenWeights = Step(model.DiscriminatorHiddenWeights, discGrads.Wh, learningRate);
        model.DiscriminatorHiddenBias = Step(model.DiscriminatorHiddenBias, discGrads.Bh, learningRate);
        model.AdversarialWeights = Step(model.AdversarialWeights, discGrads.Wadv, learningRate);
        model.AdversarialBias = Step(model.AdversarialBias, discGrads.Badv, learningRate);
        model.ClassifierWeights = Step(model.ClassifierWeights, discGrads.Wcls, learningRate);
        model.ClassifierBias = Step(model.ClassifierBias, discGrads.Bcls, learningRate);

        // ---- Generator: BCE(adv(G(y, ε)), 1) + CE(class(G(y, ε)), y) ----
        var (input, genHidden, generated) = GeneratorForward(model, fakeY, SampleNoise(fakeRows));
        var (gHidden, gAdv, gClass) = DiscriminatorForward(model, generated);
        var invFake = NumOps.FromDouble(1.0 / fakeRows);
        var gGradAdv = Engine.TensorMultiplyScalar(Engine.TensorAddScalar(Engine.TensorSigmoid(gAdv), NumOps.Negate(NumOps.One)), invFake);
        var gGradClass = Engine.TensorMultiplyScalar(Engine.TensorSubtract(Engine.Softmax(gClass, 1), OneHot(fakeY)), invFake);
        var gradGenerated = DiscriminatorBackward(model, generated, gHidden, gGradAdv, gGradClass).Input;

        var gradW2 = Engine.TensorMatMul(Engine.TensorTranspose(genHidden), gradGenerated);
        var gradB2 = Engine.ReduceSum(gradGenerated, new[] { 0 }, false);
        var gradGenHidden = Engine.TensorMultiply(
            Engine.TensorMatMul(gradGenerated, Engine.TensorTranspose(model.GeneratorOutputWeights)),
            Engine.TensorGreaterThan(genHidden, NumOps.Zero));
        var gradW1 = Engine.TensorMatMul(Engine.TensorTranspose(input), gradGenHidden);
        var gradB1 = Engine.ReduceSum(gradGenHidden, new[] { 0 }, false);

        model.GeneratorOutputWeights = Step(model.GeneratorOutputWeights, gradW2, learningRate);
        model.GeneratorOutputBias = Step(model.GeneratorOutputBias, gradB2, learningRate);
        model.GeneratorHiddenWeights = Step(model.GeneratorHiddenWeights, gradW1, learningRate);
        model.GeneratorHiddenBias = Step(model.GeneratorHiddenBias, gradB1, learningRate);
    }

    private (Tensor<T> Input, Tensor<T> Hidden, Tensor<T> Output) GeneratorForward(FedCILGenerativeModel<T> model, int[] labels, Tensor<T> noise)
    {
        int batch = labels.Length;
        var input = Engine.TensorConcatenate(new[] { OneHot(labels), noise }, 1);
        var hidden = Engine.TensorReLU(AddRow(Engine.TensorMatMul(input, model.GeneratorHiddenWeights), model.GeneratorHiddenBias, batch));
        var output = AddRow(Engine.TensorMatMul(hidden, model.GeneratorOutputWeights), model.GeneratorOutputBias, batch);
        return (input, hidden, output);
    }

    private (Tensor<T> Hidden, Tensor<T> AdversarialLogit, Tensor<T> ClassLogits) DiscriminatorForward(FedCILGenerativeModel<T> model, Tensor<T> x)
    {
        int batch = x.Shape[0];
        var hidden = Engine.TensorReLU(AddRow(Engine.TensorMatMul(x, model.DiscriminatorHiddenWeights), model.DiscriminatorHiddenBias, batch));
        var adv = AddRow(Engine.TensorMatMul(hidden, model.AdversarialWeights), model.AdversarialBias, batch);
        var cls = AddRow(Engine.TensorMatMul(hidden, model.ClassifierWeights), model.ClassifierBias, batch);
        return (hidden, adv, cls);
    }

    private (Tensor<T> Wh, Tensor<T> Bh, Tensor<T> Wadv, Tensor<T> Badv, Tensor<T> Wcls, Tensor<T> Bcls, Tensor<T> Input) DiscriminatorBackward(
        FedCILGenerativeModel<T> model, Tensor<T> x, Tensor<T> hidden, Tensor<T> gradAdv, Tensor<T> gradClass)
    {
        var hiddenT = Engine.TensorTranspose(hidden);
        var wadv = Engine.TensorMatMul(hiddenT, gradAdv);
        var badv = Engine.ReduceSum(gradAdv, new[] { 0 }, false);
        var wcls = Engine.TensorMatMul(hiddenT, gradClass);
        var bcls = Engine.ReduceSum(gradClass, new[] { 0 }, false);
        var gradHidden = Engine.TensorMultiply(
            Engine.TensorAdd(
                Engine.TensorMatMul(gradAdv, Engine.TensorTranspose(model.AdversarialWeights)),
                Engine.TensorMatMul(gradClass, Engine.TensorTranspose(model.ClassifierWeights))),
            Engine.TensorGreaterThan(hidden, NumOps.Zero));
        var wh = Engine.TensorMatMul(Engine.TensorTranspose(x), gradHidden);
        var bh = Engine.ReduceSum(gradHidden, new[] { 0 }, false);
        var input = Engine.TensorMatMul(gradHidden, Engine.TensorTranspose(model.DiscriminatorHiddenWeights));
        return (wh, bh, wadv, badv, wcls, bcls, input);
    }

    private Tensor<T> AddRow(Tensor<T> values, Tensor<T> bias, int batch)
    {
        int width = bias.Length;
        return Engine.TensorAdd(values, Engine.TensorBroadcastTo(bias.Reshape(new[] { 1, width }), new[] { batch, width }));
    }

    private Tensor<T> Step(Tensor<T> parameter, Tensor<T> gradient, T learningRate)
    {
        return Engine.TensorSubtract(parameter,
            Engine.TensorMultiplyScalar(gradient.Reshape(parameter.Shape.ToArray()), learningRate));
    }

    private Tensor<T> OneHot(int[] labels)
    {
        var values = new int[labels.Length * _numClasses];
        for (int i = 0; i < labels.Length; i++)
        {
            values[i * _numClasses + labels[i]] = 1;
        }

        return new Tensor<int>(values, new[] { labels.Length, _numClasses }).Cast<T>();
    }

    private int[] SampleFrom(int[] classes, int count)
    {
        var labels = new int[count];
        for (int i = 0; i < count; i++)
        {
            labels[i] = classes[_rng.Next(classes.Length)];
        }

        return labels;
    }

    private Tensor<T> SampleNoise(int rows)
    {
        var noise = new double[rows * _noiseDim];
        for (int i = 0; i < noise.Length; i++)
        {
            double u1 = 1.0 - _rng.NextDouble();
            double u2 = _rng.NextDouble();
            noise[i] = Math.Sqrt(-2.0 * Math.Log(u1)) * Math.Cos(2.0 * Math.PI * u2);
        }

        return new Tensor<double>(noise, new[] { rows, _noiseDim }).Cast<T>();
    }

    private Tensor<T> XavierUniform(int fanIn, int fanOut)
    {
        double limit = Math.Sqrt(6.0 / (fanIn + fanOut));
        var values = new double[fanIn * fanOut];
        for (int i = 0; i < values.Length; i++)
        {
            values[i] = (_rng.NextDouble() * 2 - 1) * limit;
        }

        return new Tensor<double>(values, new[] { fanIn, fanOut }).Cast<T>();
    }

    private void ValidateClasses(IEnumerable<int> classes, string paramName)
    {
        foreach (int c in classes)
        {
            if (c < 0 || c >= _numClasses)
            {
                throw new ArgumentException($"Class {c} is outside [0, {_numClasses}).", paramName);
            }
        }
    }

    /// <inheritdoc/>
    /// <remarks>
    /// FedCIL prevents forgetting with generative replay rather than parameter importance weighting, so every
    /// parameter gets importance 1. The <paramref name="taskData"/> is intentionally unused.
    /// </remarks>
    public Vector<T> ComputeImportance(Vector<T> modelParameters, Matrix<T> taskData)
    {
        Guard.NotNull(modelParameters);
        return Engine.TensorOnesLike(modelParameters.AsTensor()).ToVector();
    }

    /// <inheritdoc/>
    /// <remarks>
    /// With uniform importance this is a plain L2 penalty; FedCIL's own anti-forgetting term is the consistency
    /// loss (<see cref="ComputeConsistencyLoss"/>).
    /// </remarks>
    public T ComputeRegularizationPenalty(
        Vector<T> currentParameters, Vector<T> referenceParameters,
        Vector<T> importanceWeights, double regularizationStrength)
    {
        Guard.NotNull(currentParameters);
        Guard.NotNull(referenceParameters);
        Guard.NotNull(importanceWeights);

        int len = Math.Min(currentParameters.Length, referenceParameters.Length);
        if (len == 0)
        {
            return NumOps.Zero;
        }

        var current = currentParameters.Length == len ? currentParameters : currentParameters.GetSubVector(0, len);
        var reference = referenceParameters.Length == len ? referenceParameters : referenceParameters.GetSubVector(0, len);
        var diff = Engine.Subtract(current, reference);
        T penalty = Engine.DotProduct(diff, diff);

        return NumOps.Multiply(penalty, NumOps.FromDouble(regularizationStrength * 0.5));
    }

    /// <inheritdoc/>
    /// <remarks>
    /// FedCIL uses generative replay, not gradient projection; the gradient is passed through unchanged. Use
    /// <see cref="TrainClient"/> to train with replay of earlier classes.
    /// </remarks>
    public Vector<T> ProjectGradient(Vector<T> gradient, Vector<T> importanceWeights)
    {
        return gradient;
    }

    /// <inheritdoc/>
    public Vector<T> AggregateImportance(
        Dictionary<int, Vector<T>> clientImportances,
        Dictionary<int, double>? clientWeights)
    {
        Guard.NotNull(clientImportances);
        if (clientImportances.Count == 0)
        {
            throw new ArgumentException("Client importances cannot be empty.", nameof(clientImportances));
        }

        int d = clientImportances.Values.First().Length;
        var aggregated = new Vector<T>(d);
        // Normalize over the weights actually applied: participating clients, with 1.0 for a missing entry.
        double totalWeight = clientImportances.Keys.Sum(id => clientWeights?.GetValueOrDefault(id, 1.0) ?? 1.0);
        bool uniform = totalWeight <= 0;
        if (uniform)
        {
            totalWeight = clientImportances.Count;
        }

        foreach (var (clientId, importance) in clientImportances)
        {
            double w = uniform ? 1.0 : clientWeights?.GetValueOrDefault(clientId, 1.0) ?? 1.0;
            var clientImportance = importance.Length == d ? importance : importance.GetSubVector(0, d);
            aggregated = Engine.Add(aggregated, Engine.Multiply(clientImportance, NumOps.FromDouble(w / totalWeight)));
        }

        return aggregated;
    }
}

/// <summary>
/// An auxiliary-classifier GAN used by <see cref="FedCILContinualLearning{T}"/>: a conditional generator
/// G(y, ε) and a discriminator with a shared hidden layer feeding a real/fake head and a class head.
/// </summary>
/// <typeparam name="T">The numeric type for model parameters.</typeparam>
public sealed class FedCILGenerativeModel<T>
{
    internal FedCILGenerativeModel(
        Tensor<T> generatorHiddenWeights, Tensor<T> generatorHiddenBias,
        Tensor<T> generatorOutputWeights, Tensor<T> generatorOutputBias,
        Tensor<T> discriminatorHiddenWeights, Tensor<T> discriminatorHiddenBias,
        Tensor<T> adversarialWeights, Tensor<T> adversarialBias,
        Tensor<T> classifierWeights, Tensor<T> classifierBias)
    {
        GeneratorHiddenWeights = generatorHiddenWeights;
        GeneratorHiddenBias = generatorHiddenBias;
        GeneratorOutputWeights = generatorOutputWeights;
        GeneratorOutputBias = generatorOutputBias;
        DiscriminatorHiddenWeights = discriminatorHiddenWeights;
        DiscriminatorHiddenBias = discriminatorHiddenBias;
        AdversarialWeights = adversarialWeights;
        AdversarialBias = adversarialBias;
        ClassifierWeights = classifierWeights;
        ClassifierBias = classifierBias;
    }

    internal Tensor<T> GeneratorHiddenWeights { get; set; }
    internal Tensor<T> GeneratorHiddenBias { get; set; }
    internal Tensor<T> GeneratorOutputWeights { get; set; }
    internal Tensor<T> GeneratorOutputBias { get; set; }
    internal Tensor<T> DiscriminatorHiddenWeights { get; set; }
    internal Tensor<T> DiscriminatorHiddenBias { get; set; }
    internal Tensor<T> AdversarialWeights { get; set; }
    internal Tensor<T> AdversarialBias { get; set; }
    internal Tensor<T> ClassifierWeights { get; set; }
    internal Tensor<T> ClassifierBias { get; set; }

    internal IEnumerable<Tensor<T>> AllTensors()
    {
        yield return GeneratorHiddenWeights;
        yield return GeneratorHiddenBias;
        yield return GeneratorOutputWeights;
        yield return GeneratorOutputBias;
        yield return DiscriminatorHiddenWeights;
        yield return DiscriminatorHiddenBias;
        yield return AdversarialWeights;
        yield return AdversarialBias;
        yield return ClassifierWeights;
        yield return ClassifierBias;
    }
}
